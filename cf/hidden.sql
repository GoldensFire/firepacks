-- Паки, снятые с публикации, — обратно в снятые. Прогоняется выкладкой сразу
-- за заливкой паков (см. scripts/deploy-cf.js).
--
-- Зачем отдельным файлом, а не в cf/schema.sql. Схема прогоняется ДО заливки,
-- а перезаписывает status как раз заливка: таблица packages целиком приезжает
-- из домашней базы, и та про модерацию не знает — там нет ни посетителей,
-- ни комментариев, ни того, кто мог бы что-то снять. Пока пак не менялся,
-- заливка его строки не трогает и запрет держится сам; но стоит паку получить
-- новую статистику или описание, как он приедет заново со своим status = 'ok'
-- и молча вернётся в выдачу.
--
-- Почему запрет живёт в самой строке пака, а не отдельным условием в запросах:
-- все запросы сайта и так спрашивают status = 'ok' — и выдача, и поиск,
-- и счётчики, и карта сайта, и страница одного пака. Снятый пак пропадает
-- отовсюду разом, и ни одной прочитанной строки сверх прежнего это не стоит,
-- а у D1 они считаны по тарифу (см. cf/schema.sql, таблица hidden_packs).
--
-- Ключ здесь общий на пак и все его копии — тот же, что у оценок и отметок.
-- Условие status = 'ok' у первого запроса не для отбора, а для сохранности:
-- у копии стоит status = 'copy', и превратить её в 'hidden' значило бы забыть,
-- что она копия, — заливка вернула бы ей 'copy', а вот отсылку на оставшийся
-- пак (см. getCopyTarget) до тех пор было бы не найти.

UPDATE packages SET status = 'hidden'
WHERE status = 'ok'
	AND CAST(COALESCE(copy_of, id) AS TEXT) IN (SELECT pack_key FROM hidden_packs);

-- И обратно: пак, которого в списке снятых больше нет, возвращается в выдачу.
-- Снимает запрет сам раздел администрирования, прямо в базе наверху, — но если
-- строку из hidden_packs убрали как-нибудь иначе, пак не должен остаться
-- невидимым навсегда только потому, что об этом некому вспомнить.
UPDATE packages SET status = 'ok'
WHERE status = 'hidden'
	AND CAST(COALESCE(copy_of, id) AS TEXT) NOT IN (SELECT pack_key FROM hidden_packs);
