// Сверка перед выкладкой: не разошлось ли то, что лежит наверху, с тем,
// что база считает уже отправленным.
//
// ————— зачем —————
//
// Наверх уезжают только изменившиеся строки. Что именно уехало, база помнит
// сама: у каждой строки считается отпечаток, и он ложится в таблицу d1_sync
// (см. scripts/export-d1.js). Строка, чей отпечаток совпал с записанным,
// не отправляется — считается, что наверху лежит она же.
//
// Работает это ровно до тех пор, пока база одна. А она не одна. Дома, в ночном
// обходе и в ежечасном — три разных копии, которые ходят на общую полку
// и сливаются на ней по своим правилам (см. scripts/state/carry.js). Отпечатки
// путешествуют вместе с базой, и стоит слиянию оставить строку от одной копии,
// а отметку об отправке — от другой, как база начинает уверенно врать: она
// считает, что наверху лежит её строка, а лежит там чужая.
//
// Выйти из этого само оно не может никогда. Строка не меняется — значит,
// не отправляется; не отправляется — значит, наверху остаётся чужая; и так
// до скончания века, без единой жалобы, потому что жаловаться тут нечему:
// с точки зрения каждой стороны всё в порядке.
//
// Так и вышло с паком «Ночные посиделки №85» (21553). Автор удалил своё
// сообщение и выложил тот же файл заново; ночной обход в Actions прочитал тему,
// не нашёл прежнего сообщения и похоронил пак (status = 'gone'); это уехало
// наверх. Дома же пак так и остался живым — и остался с отпечатком, который
// совпадал с записанным. Пак есть в базе, есть в D1, статус у него дома «ok» —
// а на сайте его нет вовсе, и никакая следующая выкладка этого не чинит.
//
// ————— почему сверяется один только статус —————
//
// Потому что он один решает, есть пак на сайте или нет: вся выдача, все
// страницы и все счётчики отбирают по `status = 'ok'` (см. cf/src/library/).
// Разошлось описание — пак стоит на месте с прошлогодним описанием, и это
// починит первая же правка; разошёлся статус — пака нет совсем.
//
// Сверять все колонки было бы честнее и стоило бы несоизмеримо дороже: это
// вычитать всю базу из D1 каждую ночь. Здесь читаются два поля у четырнадцати
// тысяч строк — одна выборка, полторы сотни килобайт.
//
// Найденное не чинится напрямую, а забывается: у разошедшейся строки убирается
// отметка «отправлено», и обычная выгрузка следом отправляет её как изменившуюся.
// Так лечится любое расхождение, а не только замеченное здесь, — и лечится тем же
// самым путём, которым едет всё остальное.

import { DatabaseSync } from 'node:sqlite';
import path from 'node:path';
import { local, root } from './options.js';
import { readDatabase } from './d1.js';

/**
 * Сколько расхождений считать расхождениями, а не поломкой сверки.
 *
 * Мерка та же, что у обхода обсуждений (см. applyPending в src/indexer/vk-scan.js),
 * и по той же причине: единичные расхождения — это жизнь, а сотни разом означают,
 * что наверху лежит что-то другое (базу завели заново, залили не ту копию),
 * и лечить это забыванием отметок нельзя — надо выкладывать всё целиком
 * ключом --full, глазами и нарочно.
 */
const CEILING = 200;

/**
 * Сверить статусы с теми, что наверху, и забыть отметку «отправлено» у всех,
 * кто разошёлся.
 *
 * Молчит и ничего не делает там, где сверять нечего: местная копия (--local)
 * и первая выкладка, когда отметок ещё нет вовсе.
 *
 * @returns {Promise<number>} сколько строк забыто
 */
export async function forgetDrifted() {
	if (local) {
		return 0;
	}

	const db = new DatabaseSync(path.join(root, 'data', 'sibase.db'));

	try {
		const known = db.prepare(`SELECT COUNT(*) AS c FROM d1_sync WHERE tbl = 'packages'`).get().c;

		if (known === 0) {
			return 0;
		}

		const upstairs = await readDatabase('SELECT id, status FROM packages');

		if (upstairs === null) {
			console.log('Сверить статусы с базой наверху не вышло. Выкладываю как есть.');
			return 0;
		}

		const here = new Map(db.prepare('SELECT id, status FROM packages').all().map(row => [row.id, row.status]));
		const drifted = [];

		for (const row of upstairs) {
			// Строки, которой здесь нет вовсе, сверка не касается: её сносит
			// отдельный кусок выгрузки, и это другой разговор
			if (here.has(row.id) && here.get(row.id) !== row.status) {
				drifted.push(row.id);
			}
		}

		if (drifted.length === 0) {
			return 0;
		}

		if (drifted.length > CEILING) {
			console.error(`Наверху разошлись статусы у ${drifted.length} паков из ${upstairs.length}.`);
			console.error('Это не расхождение, а другая база: выкладывайте целиком — npm run deploy -- --full.');
			return 0;
		}

		const forget = db.prepare(`DELETE FROM d1_sync WHERE tbl = 'packages' AND row_id = ?`);

		db.exec('BEGIN');

		for (const id of drifted) {
			forget.run(id);
		}

		db.exec('COMMIT');

		console.log(`Статусы разошлись у ${drifted.length} паков (${drifted.slice(0, 10).join(', ')}`
			+ `${drifted.length > 10 ? ' и другие' : ''}) — отправлю их заново.`);

		return drifted.length;
	} catch (error) {
		console.error(`Сверка статусов не вышла: ${error.message}. Выкладываю как есть.`);
		return 0;
	} finally {
		db.close();
	}
}
