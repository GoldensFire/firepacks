// Ночной обход базы: собрать всё новое и выложить наверх. Одна команда,
// которую запускает расписание, — `npm run nightly`.
//
// Почему это отдельный файл, а не строчка в планировщике. Шагов два, и второй
// имеет смысл только после первого: сначала индексатор дополняет домашнюю базу
// (ВК, разбор паков, статистика, Gemini), потом выкладка увозит её в Cloudflare.
// Записанные в планировщик две команды подряд выполнились бы обе, даже если
// первая упала, — и наверх уехала бы недособранная база. Здесь же падение
// индексатора отменяет выкладку.
//
// Второе, ради чего это здесь: след. Ночной запуск некому смотреть, и без записи
// «прошло за 40 минут, добавлено 12 паков» о том, что расписание вообще работает,
// узнать неоткуда. Каждый запуск пишет свой файл в data/nightly, а сама папка
// подчищается: тридцати последних ночей хватает, чтобы понять, когда сломалось.
//
// Кончившиеся у модели суточные запросы ночь не заканчивают: индексатору отдаётся
// ключ --fallback, и он переходит на запасную модель (обе Flash-Lite, см. nextSpareModel
// в src/models.js). Запуск руками со страницы обновления так не делает.
//
// Ключи: --no-deploy — только собрать базу дома, наверх не выкладывать.
//        --no-fresh  — одним проходом по всей базе, без забега за свежим (см. ниже).
//        --fresh=N   — сколько суток считать свежими (по умолчанию 3).
//
// Всё остальное уходит индексатору как есть, поэтому ночь можно сделать легче,
// чем полный проход: `npm run nightly -- --steps=stats,recalc` обновит только
// статистику и уровни, не трогая ни ВК, ни Gemini.
//
// ————— почему проходов два —————
//
// Ночь конечна, а очередь — нет. Суточного лимита Gemini хватает на несколько
// сотен паков, нерасмеченных в базе тысячи, и всякий ночной обход обрывается
// на середине по лимиту: вопрос не в том, что успеется, а в том, что останется
// несделанным. Порядок очереди («сначала свежие», см. NEWEST_FIRST в индексаторе)
// это учитывал, но лишь внутри одного прохода — а проход этот начинался
// с обхода обсуждений и разбора всего накопившегося, и пак, выложенный вечером,
// вставал в общую очередь наравне с трёхлетними.
//
// Теперь ночь начинается с короткого забега: обойти обсуждения и сделать
// со свежевыложенными паками всё, что умеем, — разобрать, снять статистику,
// разметить, описать, докачать логотипы. Работы там на несколько десятков паков,
// то есть на считаные минуты, и упереться в лимиты она не успевает. И только
// после этого начинается длинный проход по всей остальной базе — тот самый,
// который непременно оборвётся, но оборвётся уже после того, как сегодняшнее
// сделано.
//
// Кто это запускает — дело десятое, и оба способа зовут одну и ту же команду:
//   дома   — задание Windows, его заводит scripts/schedule-nightly.ps1
//            (он же считает, во сколько по местным часам наступает час ночи
//            по Москве);
//   в облаке — GitHub Actions, .github/workflows/nightly.yml. Там перед этим
//            приезжает база, а после — уезжает обратно (см. scripts/state.js).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const logsPath = path.join(root, 'data', 'nightly');

/** Сколько последних отчётов держим. */
const KEEP_LOGS = 30;

const deploy = !process.argv.includes('--no-deploy');

/**
 * Ночь имеет право менять модель на ходу.
 *
 * Суточные запросы кончаются у Gemini на середине очереди всегда, и раньше это
 * означало конец работы: шаг сворачивался, остальное откладывалось до завтра.
 * Между тем квота считается на модель, а не на ключ — у соседней Flash-Lite
 * в этот момент лежат нетронутыми ещё пятьсот запросов. Ключ разрешает
 * индексатору взять их (см. --fallback и nextSpareModel в src/models.js:
 * запасными отмечены только обе Lite, старшие модели этим не трогаются).
 *
 * Ставится он здесь, а не в самом индексаторе, нарочно: запуск руками
 * со страницы обновления модель менять не должен — там её выбрал человек.
 */
const FALLBACK_FLAG = '--fallback';

/** Свои ключи; остальные — не наше дело, они для индексатора. */
const OWN_FLAGS = ['--no-deploy', '--no-fresh', FALLBACK_FLAG];
const indexerArgs = process.argv.slice(2).filter(arg => !OWN_FLAGS.includes(arg) && !arg.startsWith('--fresh='));

/** Сколько суток считать свежими. */
const FRESH_DAYS_DEFAULT = 3;
const freshDays = Number(process.argv.find(arg => arg.startsWith('--fresh='))?.split('=')[1]) || FRESH_DAYS_DEFAULT;

/**
 * Делать ли забег за свежим.
 *
 * Не делается он в двух случаях. Первый назван вслух ключом --no-fresh. Второй —
 * когда ночи заданы свои шаги (`--steps=stats,recalc`): забег имеет смысл только
 * у обычного полного прохода, а «обнови одну статистику» просили ровно про то,
 * что просили, и делить это надвое незачем.
 */
const doFresh = !process.argv.includes('--no-fresh')
	&& !indexerArgs.some(arg => arg.startsWith('--steps=') || arg.startsWith('--packs=') || arg.startsWith('--authors='));

/**
 * Что делается со свежими паками в первом проходе: всё, что умеем.
 *
 * Обход обсуждений здесь и есть источник свежего — без него первый проход
 * не нашёл бы ни одного нового пака. Полная статистика заменена на «только
 * у новых»: у пака, выложенного вчера, её нет вовсе, а гонять пять тысяч
 * запросов к чужому сервису ради двух десятков паков незачем — полный обход
 * статистики делает второй проход.
 */
const FRESH_STEPS = 'vk,parse,statsnew,topics,summary,logos,specials,recalc';

/**
 * Что делает второй проход: то же, что и обычная ночь, но без обхода обсуждений —
 * его уже сделал первый, и читать те же тысячи сообщений второй раз незачем.
 */
const REST_STEPS = 'parse,stats,topics,summary,recalc';

fs.mkdirSync(logsPath, { recursive: true });

const startedAt = new Date();
const stamp = startedAt.toISOString().slice(0, 19).replace(/[:T]/g, '-');
const logFile = path.join(logsPath, `${stamp}.log`);
const log = fs.createWriteStream(logFile, { flags: 'a' });

/** В файл — всегда, в окно — тоже: запуск руками должен что-то показывать. */
function say(line) {
	const text = `[${new Date().toLocaleTimeString('ru-RU')}] ${line}`;
	console.log(text);
	log.write(`${text}\n`);
}

/**
 * Запуск команды с записью всего, что она напечатала. Вывод индексатора идёт
 * в файл как есть, без отметок времени: там своя разметка ходов, и подпись
 * перед каждой строкой сделала бы её нечитаемой.
 */
function run(command, args) {
	return new Promise(resolve => {
		say(`$ ${command} ${args.join(' ')}`);

		// Без оболочки нарочно. Node у большинства стоит в «C:\Program Files\nodejs»,
		// а оболочка Windows разбирает строку по пробелам сама и находит там
		// несуществующую программу «C:\Program». Запускать здесь нечего, кроме
		// самого Node, — оболочка не нужна вовсе, и без неё пробелы не мешают.
		const child = spawn(command, args, {
			cwd: root,
			// Индексатор печатает отчёт о ходе работы отдельной разметкой — она нужна
			// странице обновления, а в файле только мусорит. Здесь её нет: переменная
			// FIREPACKS_GUI не ставится, и он пишет обычными словами.
			env: { ...process.env },
		});

		child.stdout.on('data', chunk => log.write(chunk));
		child.stderr.on('data', chunk => log.write(chunk));

		child.on('error', error => {
			say(`не вышло запустить: ${error.message}`);
			resolve(1);
		});

		child.on('close', code => resolve(code ?? 1));
	});
}

/** Старые отчёты. Держать их все незачем: за год набежит триста файлов. */
function trimLogs() {
	const files = fs.readdirSync(logsPath).filter(name => name.endsWith('.log')).sort();

	for (const name of files.slice(0, Math.max(0, files.length - KEEP_LOGS))) {
		fs.rmSync(path.join(logsPath, name), { force: true });
	}
}

const minutes = () => ((Date.now() - startedAt.getTime()) / 60000).toFixed(1);

say(`Ночной обход базы начат. Отчёт: ${logFile}`);

// Сверка с полкой — то же самое, что делает запуск сайта (см. scripts/state.js).
// Дополнять вчерашнюю копию нельзя: работа ляжет поверх устаревшего, а потом
// уедет на полку и затрёт там свежее. В Actions базу привозит отдельный шаг
// самого workflow, и второй раз её тянуть незачем.
if (!process.env.GITHUB_ACTIONS) {
	await run(process.execPath, ['--no-warnings', 'scripts/state.js', 'sync']);
}

// Первый проход: свежевыложенное, всеми средствами. Короткий — паков там
// на несколько десятков, — и потому в лимиты Gemini не упирается (см. выше).
if (doFresh) {
	say(`Сначала свежее: паки, выложенные за последние ${freshDays} суток.`);

	const fresh = await run(process.execPath, ['--no-warnings', 'src/indexer.js',
		`--steps=${FRESH_STEPS}`, `--fresh=${freshDays}`, FALLBACK_FLAG, ...indexerArgs]);

	// Сорвавшийся забег ночь не отменяет: он про несколько десятков паков,
	// а впереди вся остальная база. Молчать о нём нельзя — но и бросать
	// из-за него всё остальное было бы хуже
	if (fresh !== 0) {
		say(`Забег за свежим завершился с кодом ${fresh}. Продолжаю обычным проходом: `
			+ 'свежие паки в него всё равно попадут, просто не первыми.');
	} else {
		say(`Свежее собрано за ${minutes()} мин. Дальше — вся остальная база.`);
	}
}

// Второй проход: вся база. Без ключей индексатор делает обычный полный проход —
// ВК, разбор новых паков, статистика, тематики и краткие описания (см. STEPS
// в src/indexer.js); после забега обход обсуждений из него убран.
const restArgs = doFresh
	? [`--steps=${REST_STEPS}`, FALLBACK_FLAG, ...indexerArgs]
	: [FALLBACK_FLAG, ...indexerArgs];
const indexed = await run(process.execPath, ['--no-warnings', 'src/indexer.js', ...restArgs]);

if (indexed !== 0) {
	say(`Индексатор завершился с кодом ${indexed}. Наверх ничего не выкладываем: `
		+ 'недособранная база хуже вчерашней, которая там уже лежит.');
	trimLogs();
	log.end();
	process.exit(indexed);
}

say(`База собрана за ${minutes()} мин.`);

if (!deploy) {
	say('Выкладка отключена ключом --no-deploy. Готово.');
	trimLogs();
	log.end();
	process.exit(0);
}

const deployed = await run(process.execPath, ['--no-warnings', 'scripts/deploy-cf.js']);

if (deployed !== 0) {
	say(`Выкладка сорвалась с кодом ${deployed}. Дома база при этом собрана и цела: `
		+ 'её можно увезти наверх вручную командой npm run deploy.');
	trimLogs();
	log.end();
	process.exit(deployed);
}

say(`Готово. Всё вместе заняло ${minutes()} мин.`);
trimLogs();
log.end();
