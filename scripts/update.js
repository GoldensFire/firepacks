// Обновление базы из командной строки: собрать и тем же запуском отправить
// на сайт. Всё, что даётся сюда ключами, уходит индексатору как есть —
// `npm run stats` и `npm run index` отличаются только ими.
//
// Почему не просто `node src/indexer.js`. База у нас одна: то, что лежит дома,
// обязано лежать и на firepacks.longld342.workers.dev. Индексатор сам по себе
// правит только домашний файл, и запуск его напрямую заводил вторую базу,
// о которой никто не просил, — сегодняшнюю дома и вчерашнюю на сайте.
// Поэтому в package.json больше нет ни одной команды, зовущей индексатор
// в одиночку: все они идут сюда.
//
// Отправка не идёт, если индексатор сорвался: недособранная база хуже вчерашней,
// которая на сайте уже лежит. Оборванная же на середине отправка ничего не портит —
// база помнит, что доехало, и следующий запуск отправит недостающее (см.
// scripts/export-d1.js).
//
// То же самое, но с отчётом в файл и сверкой с полкой, делает ночной обход
// (scripts/nightly.js); то же самое с полосками на странице — кнопка «Запустить»
// (src/updater.js). Правило у всех троих одно, и оно в порядке шагов: сначала
// база, потом сайт, второе только после удачного первого.

import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Запуск с выводом прямо в окно: смотрят на него здесь же, а не в файле. */
function run(script, args = []) {
	return spawnSync(process.execPath, ['--no-warnings', path.join(root, script), ...args], {
		cwd: root,
		stdio: 'inherit',
	}).status ?? 1;
}

const indexed = run('src/indexer.js', process.argv.slice(2));

if (indexed !== 0) {
	console.error(`\nИндексатор завершился с кодом ${indexed}. На сайт ничего не отправляем: `
		+ 'недособранная база хуже вчерашней, которая там уже лежит.');
	process.exit(indexed);
}

console.log('\n───── Отправка на сайт ─────');

const deployed = run('scripts/deploy-cf.js');

if (deployed !== 0) {
	console.error(`\nОтправить на сайт не вышло (код ${deployed}). Дома всё посчитано и цело; `
		+ 'недоехавшее уйдёт следующим обновлением или командой npm run deploy.');
	process.exit(deployed);
}
