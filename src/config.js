import { settings } from './settings.js';

// Пороги и названия, общие с двойником сайта на Cloudflare, лежат в settings.js:
// тот файл ничего не знает про папки и переменные окружения, и его может прочитать
// Workers, где node:fs нет вовсе. Здесь они подмешиваются в config целиком,
// поэтому обращаться к ним как раньше — config.minGamesForDifficulty.
export * from './settings.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Секреты в этот файл не пишутся: сначала смотрим переменную окружения,
 * потом файл в папке data. Файл удобнее — положил один раз и забыл.
 */
function readSecret(envName, fileName) {
	if (process.env[envName]) {
		return process.env[envName].trim();
	}

	try {
		return fs.readFileSync(path.join(root, 'data', fileName), 'utf8').trim();
	} catch {
		return '';
	}
}

