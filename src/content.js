// Из чего пак состоит — и насколько это похоже на другой пак.
//
// Общее с Worker: отсюда живёт колонка похожих паков на странице пака
// (см. cf/src/library/similar.js), а те же поля кладёт в готовые списки
// разделов ночная сборка (см. writeLandingPages в scripts/build-web.js).
// Node-специфичного здесь нет и быть не должно — файл достижим из cf/src/**
// по импортам (см. CLAUDE.md).
//
// ————— зачем —————
//
// «Похожий пак» до сих пор означал «пак из того же раздела, самый играемый
// сверху». Это отвечало на вопрос «во что вообще играют», а не на тот, под
// которым стоит колонка: у пака про Доту и у солянки с одной темой про Доту
// раздел один и тот же, и в колонке они стояли рядом в порядке популярности.
//
// Сравнивать надо наполнение. У пака оно записано двумя списками: темы (tags)
// — то, как пак разложен на части, — и франшизы (franchises) — то, к чему
// эти части отсылают. Совпадение и там, и там означает, что вечер за столом
// пройдёт похоже; совпадение одного лишь раздела не означает ничего.
//
// К наполнению приложены ещё две мерки, которые сравнивают пак с паком, а не
// с нормой: язык и целевая аудитория. Английский пак после русского не годится
// вовсе, каким бы похожим по темам он ни был, — а пак «для тех, кому за
// тридцать, восемь из десяти мужчины» после школьного аниме-пака зовёт
// не ту компанию.
//
// И отдельно от похожести стоит второй вопрос — «а стоит ли за это садиться».
// На него отвечают наказания: обложка, спецвопросы, повторы, длина медиа
// и списанное (см. FLAW ниже). Ими пак только опускается: поднять себя этим
// нельзя.

import { jsonOrDefault } from './keys.js';
import { settings } from './settings.js';

/**
 * Сколько тем и франшиз пака едет в готовые списки разделов. Списков этих
 * полторы тысячи файлов, и хвост из редких тем весил бы в них больше, чем
 * всё остальное: сравнивать же по нему нечего — совпадают паки по главному.
 */
const KEEP_TAGS = 12;
const KEEP_FRANCHISES = 6;

/** Одно написание на все сравнения: «Дота 2» и «дота 2» — одно и то же. */
const nameKey = value => String(value ?? '').trim().toLowerCase();

/**
 * Наполнение пака строкой базы: то, что кладётся в готовый список раздела
 * и по чему потом считается похожесть.
 *
 * Франшизы приходят списком объектов ({name, themes, share}), а сюда едут
 * одними именами: доли нужны карточке, а не сравнению — «обе про Гарри
 * Поттера» одинаково верно и на трёх темах, и на тридцати.
 */
export function packContent(row) {
	return {
		tags: jsonOrDefault(row.tags, []).map(tag => String(tag ?? '')).filter(Boolean).slice(0, KEEP_TAGS),
		franchises: jsonOrDefault(row.franchises, [])
			.map(item => String(item?.name ?? item ?? '')).filter(Boolean).slice(0, KEEP_FRANCHISES),
		franchiseTop: row.franchise_top ?? null,
		// Язык — двумя буквами, как его сводит отбор выдачи (см. LANG_SQL
		// в cf/src/library/filters.js): модель, а на её молчании поле из файла.
		// Готовые списки разделов кладут его уже сведённым, из SQL
		lang: row.lang_key ?? null,
		// Кому пак: промежуток возраста и доля мужчин в процентах — оценка
		// модели по содержимому (см. audience_* в src/db.js). null у любого
		// из трёх значит «не спрашивали»: наказывать за незнание не за что
		audience: {
			from: row.audience_from ?? null,
			to: row.audience_to ?? null,
			male: row.audience_male ?? null,
		},
	};
}

/**
 * Признаки, по которым пак хуже соседа при прочих равных.
 *
 * ————— зачем колонке знать про это —————
 *
 * Похожесть отвечает на вопрос «про то же ли самое», но не на второй вопрос,
 * который человек задаёт, глядя в колонку: «а стоит ли за это садиться».
 * Три вещи на сайте отвечают на него отрицательно, и все три посчитаны заранее
 * и покрашены прямо на карточке (см. createSpecials, createDuration
 * и повторы в web/card-badges.js): много спецвопросов — пак играется не так,
 * как ждут; много повторов — вечер уходит на одно и то же; длинное медиа —
 * это уже не вопрос, а прослушивание. Пороги здесь те же самые, что красят
 * числа на карточке (см. src/settings.js): второе мнение о том, что считать
 * перебором, сайту не нужно.
 *
 * Четвёртый признак — обложка. Она ни на что в игре не влияет, но колонка
 * похожих держится на картинках: названия в ней неразличимы («Солянка 5»,
 * «Солянка № 5»), и строка без обложки читается хуже соседних просто потому,
 * что смотреть в ней не на что.
 *
 * Пятый — плагиат. Он не про то, как пак играется, а про то, стоит ли его
 * звать паком: вечер за списанной солянкой пройдёт ровно так же, как за тем
 * паком, откуда её списали, — а звать в колонке надо второй. Метка стоит
 * только у тех, у кого нашёлся хоть один чужой вопрос, и молчание в этих
 * полях — это «ничего не нашлось», а не «проверен и чист»
 * (см. plagiarism_kind в src/db.js).
 *
 * Наказание, а не отбор: пак с двумя общими франшизами и парой лишних
 * аукционов ближе к нашему, чем безупречный сосед по одной лишь тематике.
 * Отбор здесь только один и стоит он снаружи — из колонки выбрасываются паки
 * с грубым перебором, но лишь когда есть кем их заменить (см. heavyFlaw
 * в cf/src/library/similar.js).
 *
 * ————— почему числа именно такие —————
 *
 * Мерить их надо не между собой, а против того, что даёт похожесть
 * (см. WEIGHT ниже). Общая тема — это +2, общая франшиза — +3, весь раздел
 * целиком — от 0 до +4. То есть один заметный перебор (-4) съедает совпадение
 * по разделу, а грубый (-8) — совпадение по разделу вместе с парой общих тем.
 * Ровно этого и хотели: «похож, но играть в него не стоит» обязано означать
 * «стоит ниже», а не «стоит чуть ниже».
 *
 * Прежние числа (-2 и -4) этого не давали: пак с шестой частью аукционов
 * и без обложки терял шесть очков — меньше, чем даёт одна общая главная
 * франшиза, — и всё равно стоял в колонке выше опрятного соседа.
 */
const FLAW = {
	/** Нет обложки: смотреть в строке не на что. */
	noLogo: -3,
	/** Перебор — доля выше первого порога, и настоящий перебор — выше второго. */
	warn: -4,
	alarm: -8,
	/**
	 * Плагиат — тремя ступенями по доле списанного (пороги те же, что выносят
	 * приговор: см. plagiarismPartialShare и plagiarismShare в src/settings.js).
	 *
	 * Нижняя стоит на «хотя бы один чужой вопрос» и стоит дорого нарочно:
	 * это не измерение, а находка — дословно совпавший вопрос вместе с ответом
	 * и именем файла случайностью не бывает.
	 *
	 * Верхняя — «пак не свой» — весит больше, чем даёт любое совпадение
	 * по наполнению: звать читателя в копию того, что он уже читает,
	 * колонка не должна ни при каком сходстве.
	 */
	plagiarismTrace: -4,
	plagiarismPartial: -8,
	plagiarismWhole: -14,
};

/**
 * Признаки качества пака строкой базы — то, что кладётся в готовый список
 * раздела рядом с наполнением и по чему потом считается наказание.
 *
 * Доли, а не сами числа: восемь спецвопросов на пак из сорока и восемь
 * на пак из четырёхсот — это разные паки, и решает тут доля (см. пороги
 * в src/settings.js). Медиа — единственное, что едет секундами: с ним
 * сравнивают не пак, а норму, и делить его не на что.
 */
export function packQuality(row) {
	const questions = row.question_count ?? 0;
	const specials = row.special_count ?? null;

	return {
		hasLogo: row.logo_state === 'ok' && Boolean(row.logo_file),
		// null — «пак разобран до того, как это научились считать»: это не ноль,
		// и наказывать за неизвестное нельзя
		specialShare: specials !== null && questions > 0 ? specials / questions : null,
		repeatShare: row.repeat_share ?? null,
		mediaAvg: row.media_avg ?? null,
		// Плагиат — двумя числами. Сколько чужих вопросов нашлось: это отвечает
		// на вопрос «есть ли тут списанное вообще», и NULL здесь — «ничего
		// не нашлось». И какой долей своих вопросов пак нашёлся у соседей:
		// по ней и считается ступень наказания (см. plagiarismStep ниже)
		stolenQuestions: row.plagiarism_questions ?? null,
		plagiarismShare: row.plagiarism_share ?? null,
	};
}

/** Насколько число перебрало: 0 — не перебрало, 1 — заметно, 2 — грубо. */
function overStep(value, warn, alarm) {
	if (value === null || value === undefined) {
		return 0;
	}

	return value >= alarm ? 2 : (value >= warn ? 1 : 0);
}

/** Все три перебора разом: по ним же решается, выбрасывать ли пак из колонки. */
export function flawSteps(pack) {
	return [
		overStep(pack.specialShare, settings.specialWarnShare, settings.specialAlarmShare),
		overStep(pack.repeatShare, settings.repeatWarnShare, settings.repeatAlarmShare),
		overStep(pack.mediaAvg, settings.mediaWarnSeconds, settings.mediaAlarmSeconds),
	];
}

/** Как называется каждый из трёх переборов, когда счёт надо объяснить словами. */
const FLAW_NAMES = ['special', 'repeat', 'media'];

/**
 * Насколько пак списан: 0 — ничего не нашлось, 1 — единичные чужие вопросы,
 * 2 — заметная доля чужого, 3 — пак не свой.
 *
 * Отдельной ступенькой, а не долей напрямую, по той же причине, по какой
 * ступенями считаются переборы: доля 0,26 и доля 0,89 — это один и тот же
 * ответ («в паке заметная часть чужого»), и наказывать за них по-разному
 * значило бы притворяться, будто мерка точнее, чем есть.
 *
 * Считается по числу найденных чужих вопросов, а не по одной лишь доле:
 * доля бывает пустой у пака, которому нашли пару чужих вопросов при большом
 * своём составе, — а «хотя бы один факт» это именно про число.
 */
function plagiarismStep(pack) {
	if (!(pack.stolenQuestions > 0)) {
		return 0;
	}

	const share = pack.plagiarismShare ?? 0;

	if (share >= settings.plagiarismShare) {
		return 3;
	}

	return share >= settings.plagiarismPartialShare ? 2 : 1;
}

/** Во что обходится каждая ступень списанного. Нулевая — ни во что. */
const PLAGIARISM_FLAW = [0, FLAW.plagiarismTrace, FLAW.plagiarismPartial, FLAW.plagiarismWhole];

/** Ничего не записывать: обычному счёту разбор не нужен (см. weigh ниже). */
const NOTHING = () => {};

/**
 * Насколько пак хуже соседа при прочих равных — и чем именно.
 *
 * @param add куда сложить слагаемое: имя, вес и, где оно есть, насколько перебрано
 */
function weighQuality(pack, add) {
	let penalty = 0;

	if (pack.hasLogo === false) {
		penalty += FLAW.noLogo;
		add('noLogo', FLAW.noLogo);
	}

	flawSteps(pack).forEach((step, index) => {
		const value = step === 2 ? FLAW.alarm : (step === 1 ? FLAW.warn : 0);

		if (value !== 0) {
			penalty += value;
			add(FLAW_NAMES[index], value, step);
		}
	});

	const stolen = plagiarismStep(pack);

	if (stolen > 0) {
		penalty += PLAGIARISM_FLAW[stolen];
		add('plagiarism', PLAGIARISM_FLAW[stolen], stolen);
	}

	return penalty;
}

/** Насколько пак хуже соседа при прочих равных. Ноль — не хуже ничем. */
export function qualityPenalty(pack) {
	return weighQuality(pack, NOTHING);
}

/**
 * Веса — в одном месте и словами.
 *
 * Порядок между ними важнее самих чисел: пак про то же самое (franchiseTop)
 * обязан стоять выше пака, у которого просто нашлись две общие темы, а тот —
 * выше соседа по одному лишь разделу. Каждая мерка при этом считается
 * с потолком: десять общих тем не делают пак в пять раз ближе, чем две,
 * — они означают ровно то же самое, «про одно и то же».
 */
const WEIGHT = {
	/** Пак целиком про то же, что и наш: «Гарри Поттер» у обоих. */
	franchiseTop: 6,
	/** Общая франшиза — не главная, а любая из встретившихся больше раза. */
	franchise: 3,
	/** Общая тема. Их у пака десятки, поэтому вес меньше, чем у франшизы. */
	tag: 2,
	/** Сколько совпадений считается: дальше они уже ничего не добавляют. */
	maxFranchises: 3,
	maxTags: 4,
	/**
	 * Откуда сосед взялся. Раздел — тоже мерка похожести, только грубая: «паки
	 * про Доту» это несколько десятков, тема — сотни, тематика — тысячи, и
	 * совпадение с ней не говорит почти ничего.
	 */
	section: { subject: 4, tag: 2, topic: 0 },
	/** Та же сложность, соседняя ступень и всё, что дальше. */
	sameLevel: 2,
	nearLevel: 1,
	farLevel: -2,
	/**
	 * Не тот язык.
	 *
	 * «Тот» — язык самого пака, на странице которого стоит колонка, а не язык
	 * сайта и не язык посетителя. Так оно и есть на деле: за русский пак садится
	 * русская компания, и английский пак ей не подходит, каким бы похожим
	 * по темам он ни был, — а тот, кто открыл английский пак, ждёт продолжения
	 * на английском. Язык страницы тут не советчик: сайт по-английски читают
	 * и ради русских паков.
	 *
	 * Цена — как у грубого перебора: не отбор (пак с неизвестным языком
	 * не наказывается вовсе, а таких немало), но и не поправка. Играть
	 * на чужом языке нельзя вообще, а не «неудобно».
	 */
	otherLanguage: -8,
	/**
	 * Та же компания за столом — и совсем другая (см. audienceGap ниже).
	 *
	 * Мерка слабая нарочно: аудиторию называет модель по содержимому, а не
	 * статистика игр, и уверенности в ней меньше, чем в темах и франшизах.
	 * Поэтому совпадение прибавляет столько же, сколько одна общая тема,
	 * а расхождение стоит чуть дороже — но не отменяет собой сходство
	 * по наполнению.
	 */
	sameAudience: 2,
	farAudience: -3,
};

/** Где проходят границы «та же компания» и «совсем другая». */
const AUDIENCE = {
	/** Перекос по полу в процентных пунктах: до двадцати — та же компания. */
	genderNear: 20,
	genderFar: 40,
	/**
	 * Промежутки возрастов не пересеклись, но разошлись не больше чем на столько
	 * лет. Три — это «соседние компании»: «14–18» и «20–35» ещё пересекаются
	 * людьми, а «8–12» и «18–30» уже нет, и второе — другой стол целиком.
	 */
	yearsNear: 3,
};

/**
 * На сколько лет промежутки возрастов накладываются друг на друга. Число
 * отрицательное — это разрыв между ними: «12–16» и «25–40» дают -9.
 * null — у кого-то из двоих промежутка нет.
 */
function yearsOverlap(mine, theirs) {
	const known = value => value !== null && value !== undefined;

	if (!known(mine.from) || !known(mine.to) || !known(theirs.from) || !known(theirs.to)) {
		return null;
	}

	return Math.min(mine.to, theirs.to) - Math.max(mine.from, theirs.from);
}

/**
 * Насколько разные компании садятся за два пака: 0 — та же, 1 — соседняя,
 * 2 — совсем другая. null — «не спрашивали»: аудитория проставлена не у всех.
 *
 * Спрашивается это двумя вопросами сразу — про возраст и про пол, — и ответ
 * берётся худший из двух. Причина в том, что мерки эти не складываются:
 * пак для тех же тридцатилетних, но с перекосом 80/20 против 20/80 — это
 * не «наполовину та же компания», это другая компания.
 *
 * Возраст сравнивается промежутками, а не серединами: «12–18» и «16–45»
 * пересекаются, и звать из одного в другой можно, хотя середины у них
 * расходятся на пятнадцать лет. Пол — долей мужчин в процентах, женщины
 * в этих числах остальное до ста (см. audience_male в src/db.js).
 *
 * Незнание с обеих сторон честно возвращает null: пак без оценки не «средний»,
 * а неизвестный, и наказывать его не за что.
 */
export function audienceGap(source, pack) {
	const mine = source.audience ?? {};
	const theirs = pack.audience ?? {};
	const steps = [];

	if (mine.male !== null && mine.male !== undefined && theirs.male !== null && theirs.male !== undefined) {
		const apart = Math.abs(mine.male - theirs.male);

		steps.push(apart >= AUDIENCE.genderFar ? 2 : (apart >= AUDIENCE.genderNear ? 1 : 0));
	}

	const overlap = yearsOverlap(mine, theirs);

	if (overlap !== null) {
		steps.push(overlap >= 0 ? 0 : (-overlap <= AUDIENCE.yearsNear ? 1 : 2));
	}

	return steps.length > 0 ? Math.max(...steps) : null;
}

/** Сколько имён встречается в обоих списках — не больше потолка. */
function shared(mine, theirs, limit) {
	if (!mine?.size || !theirs?.length) {
		return 0;
	}

	let count = 0;

	for (const name of theirs) {
		if (mine.has(nameKey(name))) {
			count++;

			if (count >= limit) {
				break;
			}
		}
	}

	return count;
}

/**
 * Наполнение пака в том виде, в каком с ним сравнивают остальных: списки
 * сведены к одному написанию и сложены в множества. Считается один раз
 * на страницу, а не по разу на каждого из полутора сотен кандидатов.
 */
export function contentOf(pack) {
	return {
		tags: new Set((pack.tags ?? []).map(nameKey).filter(Boolean)),
		franchises: new Set((pack.franchises ?? []).map(nameKey).filter(Boolean)),
		franchiseTop: nameKey(pack.franchiseTop) || null,
		level: pack.level ?? null,
		// Язык и аудитория — не наполнение, а то, с чем наполнение сравнивают:
		// «не тот язык» и «другая компания» это ответы про пару паков, а не
		// про один. Поэтому они и живут здесь, рядом со ступенью сложности,
		// а не в наказаниях (см. weighQuality выше)
		lang: nameKey(pack.lang) || null,
		audience: pack.audience ?? null,
	};
}

/**
 * Насколько сосед похож на пак. Больше — ближе; отрицательное значит «того же
 * раздела, но ни в чём больше не совпал».
 *
 * @param {object} source наполнение самого пака (см. contentOf)
 * @param {object} pack сосед-кандидат: tags, franchises, franchiseTop, level
 * @param {string} from из какого раздела он взят: subject, tag, topic
 */
export function contentScore(source, pack, from) {
	return weigh(source, pack, from, NOTHING);
}

/**
 * На сколько ступеней сложности сосед отстоит от нашего пака. null —
 * «неизвестно»: ступень проставлена не у всех, и у большинства её нет вовсе.
 *
 * Отдельной меркой, а не одним лишь весом внутри счёта, потому что спрашивают
 * это дважды. Счёт она двигает на ступень-другую — а пак, отстоящий на две
 * ступени и больше, из колонки выбрасывается целиком, но лишь когда есть кем
 * его заменить (см. pick в cf/src/library/similar.js). «Лёгкий» после «очень
 * сложного» бывает похож на наш чем угодно, только не тем, ради чего в колонку
 * и смотрят: за него садится другая компания.
 */
export function levelGap(source, pack) {
	return source.level && pack.level ? Math.abs(source.level - pack.level) : null;
}

/**
 * Сам счёт — и, если попросили, разбор: из чего он сложился.
 *
 * Разбор идёт тем же проходом, что и счёт, нарочно. Второе место, считающее
 * то же самое ради объяснения, разошлось бы с первым на первой же правке
 * весов — и объяснение врало бы молча, а поймать это некому: смотрит в него
 * один человек, хозяин сайта, и смотрит редко.
 *
 * @param add куда сложить слагаемое: имя, вес и, где оно есть, число совпадений
 */
function weigh(source, pack, from, add) {
	let score = 0;

	// Откуда сосед взялся. Имя слагаемого называет и сам раздел: «оба целиком
	// про Доту» и «нашлись в одной теме» — разные ответы, и разбор, в котором
	// они выглядят одинаково, не объясняет ничего
	const section = WEIGHT.section[from] ?? 0;

	if (section !== 0) {
		score += section;
		add('section:' + from, section);
	}

	const top = nameKey(pack.franchiseTop);

	// Оба пака целиком про одно и то же — это самое сильное, что о похожести
	// вообще можно сказать, и никакое число общих тем этого не перевешивает
	if (top && source.franchiseTop && top === source.franchiseTop) {
		score += WEIGHT.franchiseTop;
		add('franchiseTop', WEIGHT.franchiseTop);
	}

	const franchises = shared(source.franchises, pack.franchises, WEIGHT.maxFranchises);

	if (franchises > 0) {
		score += franchises * WEIGHT.franchise;
		add('franchise', franchises * WEIGHT.franchise, franchises);
	}

	const tags = shared(source.tags, pack.tags, WEIGHT.maxTags);

	if (tags > 0) {
		score += tags * WEIGHT.tag;
		add('tag', tags * WEIGHT.tag, tags);
	}

	// Сложность — поправка, а не отбор. Неоценённых паков в библиотеке
	// большинство, и спрашивать с них ступень значило бы выбросить большинство
	const gap = levelGap(source, pack);

	if (gap !== null) {
		const value = gap === 0 ? WEIGHT.sameLevel : gap === 1 ? WEIGHT.nearLevel : WEIGHT.farLevel;

		score += value;
		add('level', value, gap);
	}

	// Язык. Наказание одностороннее: за свой язык не прибавляется ничего —
	// он и так подразумевается, — а за чужой снимается сразу много. Неизвестный
	// язык (у одного из двоих или у обоих) не наказывается: «unknown» это
	// не язык, а молчание, и таких паков в библиотеке хватает
	const lang = nameKey(pack.lang);

	if (source.lang && lang && source.lang !== 'unknown' && lang !== 'unknown' && source.lang !== lang) {
		score += WEIGHT.otherLanguage;
		add('language', WEIGHT.otherLanguage);
	}

	// Целевая аудитория: та же компания за столом или другая (см. audienceGap)
	const crowd = audienceGap(source, pack);

	if (crowd !== null && crowd !== 1) {
		const value = crowd === 0 ? WEIGHT.sameAudience : WEIGHT.farAudience;

		score += value;
		add('audience', value, crowd);
	}

	// И последнее — не про похожесть, а про то, стоит ли за это садиться:
	// обложка, спецвопросы, повторы, длина медиа и списанное
	// (см. weighQuality выше). Число тут всегда отрицательное или ноль:
	// поднять пак этим нельзя, можно только опустить
	return score + weighQuality(pack, add);
}

/**
 * Тот же счёт, но со слагаемыми: чем сосед заслужил своё место в колонке
 * и чем его потерял.
 *
 * Наружу это едет только хозяину сайта и только на те паки, что и так
 * отдаются (см. similarPacks в cf/src/library/similar.js): колонка держится
 * на числе, которого не видно, и «почему вот этот здесь, а вон тот нет» —
 * вопрос, на который иначе отвечать нечем.
 *
 * @returns {{score: number, parts: Array<{key: string, value: number, count?: number}>}}
 */
export function scoreParts(source, pack, from) {
	const parts = [];

	const score = weigh(source, pack, from, (key, value, count) => parts.push(
		count === undefined ? { key, value } : { key, value, count },
	));

	return { score, parts };
}
