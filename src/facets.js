// Что из настроек сайта уезжает в браузер, а что остаётся серверу.
//
// Настройки (см. getFacets в cf/src/library/pages.js и в src/server/pages.js)
// собираются один раз и одним объектом: пороги, названия тематик, счётчики
// по уровням, список типов «пак целиком про одно» — и заодно полный список тем
// всех паков. Первое нужно колонке фильтров и карточкам, последнее — не нужно
// в браузере никому.
//
// Список тем длинный: тысяча восемьсот сорок шесть названий, семьдесят семь
// килобайт — восемьдесят девять процентов всего ответа /api/facets. При этом
// в web/*.js нет ни одного чтения facets.tags: `state.tags` в library-query.js
// — это отмеченные человеком темы, а не список всех. То есть эти семьдесят
// семь килобайт приезжали на каждую страницу, разбирались браузером и
// выбрасывались.
//
// Читают список двое, и оба — на сервере, вызовом функции, а не по HTTP:
// tagPages в scripts/build-web.js (складывает страницы тем в prebuilt.json)
// и listTagPages в src/server/pages.js (то же самое дома). Worker за ними
// ходит уже в prebuilt.json, а не сюда (см. listTagPages
// в cf/src/library/pages.js). Поэтому убрать их из ответа можно, ничего
// не сломав, — и нельзя убрать из самого getFacets, откуда их берут те двое.
//
// Отдельным файлом, а не тремя одинаковыми строчками по местам: мест, где
// настройки становятся ответом, три — /api/facets в Worker, homeBoot там же
// и /api/facets дома, — и разойдись они, разница вылезла бы не ошибкой,
// а лишними килобайтами на одной из страниц. Ровно та же причина, по которой
// список типов «целиком про одно» вынесен в свой /api/subjects.
//
// Node-специфичного здесь нет и быть не может: файл достижим из cf/src/index.js.

