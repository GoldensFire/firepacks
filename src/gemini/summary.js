/**
 * На каком языке написан пак.
 *
 * Раньше язык брался из самого файла — из поля, которое ставит редактор,
 * а не автор. По умолчанию там стоит язык системы, и оттого в базе английских
 * паков было больше, чем их есть на свете, а половина числилась «без указания».
 * Фильтр «Язык пака» на этом враньё и строился.
 *
 * Спрашивается вместе с описанием и аудиторией, тем же запросом и по тому же
 * списку тем: это ещё одна вещь про пак целиком, и отдельного запроса
 * (а значит, и куска суточного лимита) она не стоит.
 *
 * Главная ловушка здесь — названия. Пак про западную музыку весь состоит
 * из английских строк в ответах, оставаясь при этом русским паком: вопросы,
 * темы и подписи в нём русские, а «Bohemian Rhapsody» — это название, которое
 * не переводят ни на каком языке. Про это в правилах сказано отдельно и дважды.
 */
export const LANGUAGE_RULES = `Правила:
- Ответ — код языка (поле lg), одно значение из списка:
${LANGUAGE_KEYS.map(key => `  ${key} — ${LANGUAGE_NAMES[key]}`).join('\n')}
  Ничего из списка не подходит или языка не видно — пустая строка.
- Смотри на ТЕКСТ: на тексты вопросов, на названия тем, на название пака,
  на описание автора и на ответы. Именно на языке этих строк пак и написан.
- Ответы важнее всего прочего, а первый ответ важнее остальных. В ответе часто
  написано несколько вариантов подряд — через слэш, через запятую, в скобках:
  «Тетрадь смерти / Death Note», «Ведьмак (The Witcher)». Язык пака определяет
  ПЕРВЫЙ из них: он основной, остальные — уточнение и перевод.
- Название произведения языком пака НЕ является. Русский пак про западную
  музыку весь состоит из английских строк: «Nirvana», «Smells Like Teen Spirit»,
  «Queen». Это имена собственные, их не переводят, и они не делают пак
  английским. Кинопак с ответами «Interstellar» и «Inception» — ровно то же
  самое. Смотри, на каком языке написано ВОКРУГ названий: сами вопросы, темы,
  подписи, пояснения в скобках.
- Так же и наоборот: английский пак, где в ответах названы русские фильмы,
  остаётся английским.
- Если русского и английского вперемешку поровну, а вопросы и темы русские —
  это ru. Язык пака — это язык, на котором с игроком разговаривают.
- Не гадай по тематике: аниме-пак не японский, пак про Голливуд не английский.
  Паки для «Своей игры» пишут почти сплошь по-русски, и обратное должно быть
  видно прямо в тексте.`;

const SUMMARY_INSTRUCTION = `Ты описываешь пакеты вопросов для игры «Своя игра».
Работы три, и делаются они по одному и тому же списку тем.

Тебе дают название пака, теги, описание автора и список тем. У каждой темы после
тире идёт выжимка её содержимого: ответы на вопросы и куски самих вопросов,
через « / ». Именно она и говорит, о чём пак на самом деле.

${PACK_CONTEXT}

ПЕРВОЕ — опиши весь пак одной короткой фразой (поле s): по ней человек поймёт,
что внутри.
${SUMMARY_RULES}

ВТОРОЕ — назови целевую аудиторию пака: возраст и пол тех, кому он интересен.
${AUDIENCE_RULES}

ТРЕТЬЕ — назови язык, на котором пак написан (поле lg).
${LANGUAGE_RULES}`;

export const AUDIENCE_FIELDS = {
	af: { type: 'INTEGER' },
	at: { type: 'INTEGER' },
	mp: { type: 'INTEGER' },
	// Язык пака по его тексту, а не по полю в файле: то поле ставит редактор
	// (см. LANGUAGE_RULES). Едет вместе с аудиторией, потому что спрашивается
	// тем же запросом и по тому же списку тем
	lg: { type: 'STRING' },
};

const SUMMARY_SCHEMA = {
	type: 'OBJECT',
	properties: { s: { type: 'STRING' }, ...SUMMARY_TRANSLATIONS, ...AUDIENCE_FIELDS },
	required: ['s', ...Object.keys(SUMMARY_TRANSLATIONS), 'af', 'at', 'mp', 'lg'],
};

/** Код языка из ответа модели: только тот, что есть в списке. */
export function cleanLanguage(value) {
	const key = String(value ?? '').trim().toLowerCase().slice(0, 2);
	return LANGUAGE_KEYS.includes(key) ? key : null;
}

/** Крайние значения, за которыми ответ модели считается промахом, а не оценкой. */
const AGE_MIN = 6;
const AGE_MAX = 70;

/**
 * Насколько широким разрешено быть промежутком возраста.
 *
 * Ради этого числа всё и сужалось. «20–35» на карточке не значит ничего: под него
 * подходит кто угодно, и два совершенно разных пака подписаны им одинаково.
 * Пять лет заставляют модель назвать середину — то самое, чем пак про игры
 * нулевых отличается от пака про игры двадцатых.
 */
const AGE_SPREAD = 5;

/**
 * Проверяет возраст и пол, названные моделью.
 *
 * Всё, что не разобралось, обнуляется целиком: половина оценки — «возраст есть,
 * пола нет» — на карточке не значит ничего, а место занимает.
 *
 * Слишком широкий промежуток не выбрасывается, а сужается вокруг своей середины:
 * модель, ответившая «20–35», о возрасте всё-таки что-то сказала, и «26–31»
 * из этого ответа честнее пустого места. Правило при этом остаётся в запросе:
 * сужение здесь — страховка, а не способ работы.
 *
 * @returns {{from: number, to: number, male: number}|null}
 */
export function cleanAudience(answer) {
	let from = Math.round(Number(answer?.af));
	let to = Math.round(Number(answer?.at));
	const male = Math.round(Number(answer?.mp));

	if (![from, to, male].every(Number.isFinite)) {
		return null;
	}

	if (from < AGE_MIN || to > AGE_MAX || from > to || male < 0 || male > 100) {
		return null;
	}

	if (to - from > AGE_SPREAD) {
		const middle = (from + to) / 2;
		from = Math.max(AGE_MIN, Math.round(middle - AGE_SPREAD / 2));
		to = from + AGE_SPREAD;
	}

	return { from, to, male };
}

/**
 * Краткая суть пака одной строкой: «Вселенная Гарри Поттера», «Логотипы компаний».
 *
 * Модель смотрит не только на названия тем и теги, но и на выжимку содержимого
 * каждой темы — ответы и куски текстов вопросов (её собирает buildSample в siq.js).
 * Без неё описание получалось про названия, а названия тем в «Своей игре» шуточные
 * и о содержимом не говорят ничего.
 *
 * Заодно тем же запросом спрашивается целевая аудитория пака (см. AUDIENCE_RULES):
 * вопрос задаётся по тому же списку тем, и отдельного запроса он не стоит.
 *
 * @param {{name: string, themes: Array<{name: string, sample: string}>}} pack
 * @returns {Promise<{summary: string, audience: {from: number, to: number, male: number}|null}>}
 *   описание (пустая строка, если сказать нечего) и оценка аудитории
 */
export async function describePack(pack) {
	const themes = pack.themes.slice(0, config.summaryThemeLimit).map(theme => {
		const sample = theme.sample ? ` — ${theme.sample.slice(0, config.summarySampleLimit)}` : '';
		return `- ${theme.name}${sample}`;
	});

	// Тем нет вовсе — спрашиваем всё равно, по названию и тегам. Пак без разобранных
	// тем ничем не заслужил остаться единственным без описания, а сказать по одному
	// названию модели чаще всего есть что; не найдёт смысла — вернёт пустую строку.
	if (themes.length === 0 && !pack.name) {
		return { summary: '', audience: null, language: null };
	}

	const cut = pack.themes.length > themes.length ? `\n(и ещё ${pack.themes.length - themes.length} тем)` : '';
	const list = themes.length > 0
		? `\nТемы:\n${themes.join('\n')}${cut}`
		: '\n(тем в паке разобрать не удалось: суди по названию и тегам, а не найдёшь смысла — верни пустую строку)';
	const prompt = `${SUMMARY_INSTRUCTION}\n\nПак: «${pack.name}»${packAbout(pack)}${list}`;

	const { value } = await ask(prompt, SUMMARY_SCHEMA);

	return {
		summary: cleanSummary(value?.s),
		translations: cleanTranslations(value),
		audience: cleanAudience(value),
		language: cleanLanguage(value?.lg),
	};
}

/** Модель нет-нет да и обернёт фразу в кавычки или закончит точкой. */
export function cleanSummary(value) {
	return String(value ?? '')
		.replace(/\s+/g, ' ')
		.trim()
		.replace(/^[«"']|[»"']$/g, '')
		.replace(/\.$/, '')
		.slice(0, 120);
}
