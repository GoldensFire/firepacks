// Докуда ежечасный обход дочитал обсуждения в прошлый раз.
//
// Отдельным файлом потому, что спрашивают отметку с двух сторон и по разным
// поводам. Ключи (src/indexer/options.js) спрашивают её ДО работы — чтобы
// посчитать, с какого мига начинать; обход обсуждений (src/indexer/vk-scan.js)
// пишет её ПОСЛЕ, и только если тему и вправду дочитал. Держи её в любом
// из двух — и второй ходил бы к первому за тем, что к нему не относится.
//
// ————— зачем она вообще —————
//
// Ежечасный обход читает не всю тему, а хвост: сообщения не старше отсечки
// (см. readTopicSince в src/vkapi.js). Отсечка до сих пор считалась от часов —
// «сутки назад» плюс сутки запаса, — и это работало ровно до тех пор, пока
// обход приходил каждый час. Но расписание GitHub — обещание, а не будильник:
// при общей загрузке часть запусков пропускается вовсе, и пропуск на трое
// суток означал, что двое из них хвост уже не покрывает. Пак, выложенный
// в такую дыру, не находился ни в тот час, ни в любой следующий — его
// подбирала только ночь, читающая тему целиком.
//
// Отметка чинит это тем, что меряет не часы, а сделанное: следующий обход
// начинает оттуда, где кончил предыдущий, сколько бы между ними ни прошло.
// Ходит обход каждый час — читает час; не приходил трое суток — прочитает
// трое суток и ничего не потеряет.
//
// ————— почему отметка одна, а не по теме на каждую —————
//
// Потому что ставится она по концу всего обхода, а не по концу темы. Обход
// читает темы одну за другой в одном проходе, и запуск либо дошёл до конца,
// либо сорвался; сорвавшемуся верить нельзя ни по одной теме — недочитанная
// тема и дочитанная выглядят у него одинаково. Хранить три отметки, которые
// всегда двигаются вместе, значит завести три способа рассказать одно и то же.

import { getSetting, setSetting } from '../db.js';

const TAIL_KEY = 'vk_tail_at';

/**
 * Насколько раньше своего конца отметка ставится назад.
 *
 * Обход читает тему не мгновенно, и сообщение, написанное, пока он идёт, могло
 * лечь в уже прочитанное окно, а могло и не лечь. Отметка «докуда дочитали»
 * поэтому ставится не на миг окончания, а на четверть часа раньше: сообщение,
 * попавшее в эту щель, следующий обход прочитает второй раз — и ничего с ним
 * не сделает, потому что пак с таким документом в базе уже есть.
 *
 * Пятнадцать минут — с запасом на всё сразу: и на сам обход (он укладывается
 * в секунды), и на расхождение часов ВК с нашими.
 */
const OVERLAP_MS = 900_000;

/**
 * Миг, до которого прошлый обход тему дочитал. null — отметки нет вовсе:
 * так выглядит и первый запуск, и база, приехавшая с полки постарше.
 */
export function tailReadUntil() {
	const stored = Number(getSetting(TAIL_KEY));

	return Number.isFinite(stored) && stored > 0 ? stored : null;
}

/**
 * Запомнить, что темы дочитаны до этого мига. Зовётся только тем обходом,
 * который и вправду дочитал: сорвавшийся отметку не двигает, иначе пропущенное
 * им стало бы пропущенным навсегда.
 *
 * @param {number} at миг начала обхода — не конца (см. OVERLAP_MS)
 */
export function noteTailRead(at) {
	setSetting(TAIL_KEY, String(Math.max(0, at - OVERLAP_MS)));
}
