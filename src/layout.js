// Не та раскладка: «вщеф 2» — это «dota 2», набранное русскими буквами.
//
// Это не транслитерация и не опечатка. Транслитерация переводит звуки («дота» →
// «dota»), а тут переводятся клавиши: человек нажал те самые кнопки, на которых
// написано d-o-t-a, но переключить раскладку забыл — и получил «вщеф». Слов
// таких в языке нет вовсе, и найтись по ним не может ничего.
//
// Внутренний поиск это подтвердил: «вщеф 2» набирали семь раз за шестнадцать
// дней — столько же, сколько «Музыкальный пакчач» и «караоке». Все семь
// вернулись пустыми.
//
// Почему не хватало того, что уже есть. Транслитерация в поиске стоит давно
// (см. toLatin в src/subject.js), но она про другое: toLatin('дота') даёт
// «dota» и находит, а toLatin('вщеф') даёт «vschef» — набор букв, которого нет
// нигде. Нужна вторая таблица, и она не выводится из первой: одна про звуки,
// другая про расположение клавиш.
//
// Node-специфичного здесь нет: этим пользуется и Worker (через src/fuzzy.js).

/**
 * Русская буква → латинская, стоящая на той же клавише. ЙЦУКЕН против QWERTY,
 * три ряда сверху вниз.
 *
 * «ё» тут тоже есть, хотя поиск сводит её к «е» раньше (см. normalizeText
 * в src/fuzzy.js): таблица описывает клавиатуру, а не то, что с ней потом
 * делают, и дырка в ней однажды обошлась бы дороже лишней строки.
 */
const RU_TO_EN = {
	'й': 'q', 'ц': 'w', 'у': 'e', 'к': 'r', 'е': 't', 'н': 'y', 'г': 'u', 'ш': 'i', 'щ': 'o', 'з': 'p',
	'х': '[', 'ъ': ']',
	'ф': 'a', 'ы': 's', 'в': 'd', 'а': 'f', 'п': 'g', 'р': 'h', 'о': 'j', 'л': 'k', 'д': 'l',
	'ж': ';', 'э': "'",
	'я': 'z', 'ч': 'x', 'с': 'c', 'м': 'v', 'и': 'b', 'т': 'n', 'ь': 'm',
	'б': ',', 'ю': '.', 'ё': '`',
};

/** Она же наоборот. Собирается из первой, чтобы две таблицы не разошлись. */
const EN_TO_RU = Object.fromEntries(Object.entries(RU_TO_EN).map(([ru, en]) => [en, ru]));

/**
 * То же самое, но набранное в другой раскладке. Пустая строка — «переводить
 * тут нечего».
 *
 * Переводится только слово целиком и только одним алфавитом: «вщеф» — да,
 * «dотa» — нет. Смешанное слово это либо опечатка, с которой разберётся общий
 * поиск с допуском, либо чужое название вроде «Dота» — и подменять в нём буквы
 * значило бы искать то, чего человек не набирал.
 *
 * Короткие слова не переводятся вовсе. Поиск по переведённому идёт вхождением,
 * без прощения опечаток, и «в» → «d» нашло бы каждый пак, где есть латинская
 * «d», то есть половину базы.
 */
const MIN_LENGTH = 3;

export function switchLayout(text) {
	const word = String(text ?? '').toLowerCase();

	if (word.length < MIN_LENGTH) {
		return '';
	}

	const table = /^[а-яё]+$/.test(word)
		? RU_TO_EN
		: (/^[a-z]+$/.test(word) ? EN_TO_RU : null);

	if (!table) {
		return '';
	}

	let out = '';

	for (const char of word) {
		// Клавиша без пары — вся затея развалилась: половина слова переведена,
		// половина нет, и получилось третье слово, которого не набирал никто
		if (!Object.hasOwn(table, char)) {
			return '';
		}

		out += table[char];
	}

	return out;
}
