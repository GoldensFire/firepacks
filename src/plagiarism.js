// Кто у кого списал. Отпечатки тем, поиск донора и приговор паку.
//
// Отдельным модулем — по той же причине, что topics.js и franchise.js: здесь
// одна арифметика и ни одного похода ни в базу, ни в сеть. На вход подаются
// строки паков как они лежат в packages, на выход — приговоры; читает базу
// и пишет в неё шаг plagiarism в src/indexer.js.
//
// ————— что вообще сравнивается —————
//
// Текста вопросов в базе нет: разборщик читает его и выбрасывает (см. src/siq.js).
// Зато у каждой темы каждого пака лежит огрызок её содержимого — поле sample,
// сведённые через « / » ответы и куски вопросов, ради которого всё и затевалось:
// по нему модель размечает тематики. Для темы он почти так же неповторим, как
// отпечаток пальца: «Кэпком / Аркейн / Фромсофтвер / СОни) / Супержайнт» — это
// не «тема про игроразработчиков вообще», это вот эта конкретная тема вот этого
// человека, со всеми его опечатками.
//
// Поэтому мельче темы этот модуль не смотрит, и это не временная мера до этапа 1:
// сайт мельче темы ничего не показывает (см. roundsForApi в src/keys.js), так что
// метка тоньше темы ему всё равно негде было бы поместиться.
//
// ————— почему сравниваются числа, а не строки —————
//
// Тем в базе четверть миллиона, и сравнивать их попарно — это часы. Сравнивается
// восьмибайтное число: первые восемь байт SHA-1 от склейки приведённых к общему
// виду названия и образца. Восьми байт хватает с запасом — на полутора миллионах
// отпечатков вероятность случайного совпадения двух разных примерно пять
// стомиллионных долей процента, то есть на несколько порядков реже, чем
// вероятность, что два человека независимо написали дословно одну и ту же тему
// с теми же ответами.
//
// Тот же самый счёт готовится и для вопросов (этап 1): там в склейку добавятся
// текст вопроса и имя медиафайла, а всё остальное — приведение, разложение
// в память, поиск донора, приговор — остаётся ровно этим.

import crypto from 'node:crypto';
import { buildAuthorKey } from './keys.js';

/**
 * Строка, приведённая к скелету: нижний регистр, «ё» — «е», всё, что не буква
 * и не цифра, схлопнуто в один пробел, края обрезаны.
 *
 * Без этого «Кто изображён на фото?» и «кто изображен на фото» были бы двумя
 * разными темами, а списавший — невиновным. Знаки препинания выброшены нарочно:
 * при переносе пака из редактора в редактор кавычки и тире меняются сами собой,
 * и держаться за них значит ловить только тех, кто копировал файл целиком.
 */
export function skeleton(text) {
	return String(text ?? '')
		.toLowerCase()
		.replace(/ё/g, 'е')
		.replace(/[^\p{L}\p{N}]+/gu, ' ')
		.trim();
}

/**
 * Отпечаток темы: sha1(имя + "\0" + образец)[0..8] одним 64-битным числом.
 *
 * Нулевой байт между кусками стоит не для красоты. Без него тема «Аниме»
 * с образцом «опенинги» и тема «Анимеопенинги» с пустым образцом дали бы один
 * и тот же отпечаток — а это разные темы.
 *
 * Пустая тема отпечатка не получает вовсе (null): у пака, разобранного до того,
 * как темы стали храниться объектами, образца нет, и все его темы сошлись бы
 * в одну «пустую», которая тут же стала бы общим местом на пол-базы.
 */
export function themeFingerprint(name, sample) {
	const body = `${skeleton(name)}\0${skeleton(sample)}`;

	if (body === '\0') {
		return null;
	}

	return crypto.createHash('sha1').update(body).digest().readBigUInt64BE(0);
}

/**
 * Темы пака с их местом в раундах. Место нужно затем, чтобы потом проставить
 * заимствованной теме донора прямо в rounds (поле src), — карточка показывает
 * темы именно оттуда.
 *
 * Повторы внутри одного пака схлопываются: тема, стоящая в паке дважды, — это
 * одна тема, и считать её за две значило бы дарить долю тому, кто повторился.
 * Место запоминается за всеми повторами сразу, чтобы метку получили оба.
 */
export function packThemes(rounds) {
	const themes = new Map();

	(rounds ?? []).forEach((round, roundIndex) => {
		(round?.themes ?? []).forEach((theme, themeIndex) => {
			const fp = typeof theme === 'string'
				? themeFingerprint(theme, '')
				: themeFingerprint(theme?.name, theme?.sample);

			if (fp === null) {
				return;
			}

			const known = themes.get(fp);

			if (known) {
				known.push([roundIndex, themeIndex]);
			} else {
				themes.set(fp, [[roundIndex, themeIndex]]);
			}
		});
	});

	return themes;
}

/**
 * Кто раньше. По отметке времени сообщения ВК, а при равных отметках —
 * по меньшему номеру.
 *
 * Номер строки старшинством не является, и это не мелочь: номера раздаёт
 * порядок обхода обсуждений, темы читаются с конца, а старое подбирается
 * потом — пак 2019 года запросто получает номер больше, чем пак 2026-го.
 * Судить по номеру значило бы объявить вором того, кто выложил первым.
 *
 * Пак без отметки времени старшим не бывает: про него неизвестно, когда он
 * появился, и назначать его источником — значит выдумывать. Такой пак остаётся
 * в базе обычным паком, просто донором ни для кого не становится.
 */
function earlier(a, b) {
	if (a.ts === null) {
		return false;
	}

	if (b.ts === null) {
		return true;
	}

	return a.ts === b.ts ? a.id < b.id : a.ts < b.ts;
}

/**
 * Один ли это человек. Три признака, и достаточно любого.
 *
 * Страница ВК (vk_author_url) — главный: имена в ВК меняют, адрес страницы нет.
 * Подпись внутри файла (authors_key) ловит того, кто перевыложил свой же пак
 * с другого аккаунта, не тронув файла.
 *
 * Третий — имя автора сообщения — добавлен по живому случаю и снимает ровно
 * одного: «Общие знания №3» Станислава Бонанчика списан у «SIGame
 * Развлекательный №2» Станислава Бонанчика. Две разные страницы ВК
 * (bonanchik04 и id863765889), две разные подписи в файле («Lord» и
 * «Lord_Buba») — и очевидно один человек. Без этой проверки в улове сидел бы
 * он, а не вор.
 *
 * Пустые значения не сравниваются вовсе: пак без подписи в файле совпал бы
 * по ней с половиной базы, и вся проверка выродилась бы в «все свои».
 */
function samePerson(a, b) {
	return (a.url !== '' && a.url === b.url)
		|| (a.authors !== '' && a.authors === b.authors)
		|| (a.author !== '' && a.author === b.author);
}

/**
 * Пак в том виде, в каком его читает разбор: только то, по чему выносится
 * приговор, и ничего больше. Тяжёлое поле rounds здесь уже разложено
 * в отпечатки и дальше не держится.
 */
function toEntry(row) {
	return {
		id: row.id,
		name: row.name ?? '',
		ts: row.vk_ts ?? null,
		url: (row.vk_author_url ?? '').trim(),
		author: buildAuthorKey(row.vk_author ?? ''),
		authors: buildAuthorKey(row.authors_key ?? ''),
		themes: packThemes(row.rounds),
	};
}

/**
 * Сколько доноров запоминается у пака. Больше пяти не нужно никому: список
 * едет наверх вместе с паком и читается человеком на карточке, а солянка
 * из десяти чужих паков — это уже не «откуда взято», а простыня.
 */
const MAX_SOURCES = 5;

/** Доля до тысячных — как и везде в этом проекте (см. topics.js). */
const round = value => Math.round(value * 1000) / 1000;

/**
 * Полный пересмотр базы: кто у кого списал.
 *
 * Пересмотр именно полный, и добором его не заменить. Пак, найденный сегодня
 * в старой теме обсуждения и выложенный в 2019 году, меняет старшинство сразу
 * у всех, кого уже проверили: вчерашний «первоисточник» оказывается вором.
 * Поэтому шаг всякий раз раскладывает базу заново — это семь секунд и ни одного
 * похода в сеть, а половинчатая проверка врала бы уверенно.
 *
 * Строки берутся любым перечислением, а не готовым массивом, нарочно: у пака
 * в поле rounds лежат килобайты разбора, и вся база разом — это полтораста
 * мегабайт. Здесь от каждого пака остаются одни отпечатки (по восемь байт
 * на тему), а разобранные раунды живут ровно до конца своего витка. Индексатор
 * этим и пользуется: читает базу потоком (см. шаг plagiarism).
 *
 * @param {Iterable} rows строки packages: id, name, vk_ts, vk_author,
 *        vk_author_url, authors_key, rounds (уже разобранные, см. normalizeRounds)
 * @param {object} limits пороги из settings.js
 * @returns {{verdicts: Map<number, object>, stats: object}} приговоры только
 *        у отмеченных паков; у остальных метки нет, и это не то же самое, что
 *        «проверен и чист» — это «под правило не подошёл»
 */
export function reviewPlagiarism(rows, limits) {
	const entries = [];

	for (const row of rows) {
		entries.push(toEntry(row));
	}

	// Кто где встречается. Ключ — отпечаток темы, значение — паки, в которых
	// она есть. Четверть миллиона ключей и столько же коротких списков: это
	// и есть та самая «разложенная в память база»
	const holders = new Map();

	for (const entry of entries) {
		for (const fp of entry.themes.keys()) {
			const known = holders.get(fp);

			if (known) {
				known.push(entry);
			} else {
				holders.set(fp, [entry]);
			}
		}
	}

	// Общее место: тема, встречающаяся в стольких паках, — фольклор своей игры,
	// а не чья-то собственность. «Что тяжелее, килограмм пуха или килограмм
	// железа» принадлежит всем. Такие отпечатки выбрасываются совсем — и из
	// числителя, и из знаменателя: считать их заимствованными нельзя, но и
	// записывать паку в заслугу как «свою тему» тоже
	const common = new Set();

	for (const [fp, list] of holders) {
		if (list.length >= limits.plagiarismCommonPacks) {
			common.add(fp);
		}
	}

	// Донор темы — тот, у кого она стоит раньше всех. Сортируем держателей
	// один раз здесь, а не ищем самого раннего на каждую тему каждого пака:
	// дальше остаётся сравнение двух пар чисел
	for (const list of holders.values()) {
		list.sort((a, b) => (earlier(a, b) ? -1 : 1));
	}

	const verdicts = new Map();
	const stats = { packs: 0, withThemes: 0, fingerprints: holders.size, common: common.size, flagged: 0 };

	for (const entry of entries) {
		stats.packs++;

		if (entry.themes.size > 0) {
			stats.withThemes++;
		}

		// Свои темы — всё, кроме общих мест
		const own = [...entry.themes.keys()].filter(fp => !common.has(fp));

		// Пак из четырёх тем, списанный целиком, — это «сто процентов», которым
		// цена ноль: столько тем сходится и по случайности
		if (own.length < limits.plagiarismMinThemes) {
			continue;
		}

		// Откуда взята каждая заимствованная тема и сколько тем дал каждый донор
		const marks = [];
		const byDonor = new Map();

		for (const fp of own) {
			// Держатели уже отсортированы по старшинству, поэтому первый же чужой
			// и более ранний — и есть донор. Свои паки пропускаются молча:
			// перевыложить собственный пак со второго аккаунта — не воровство
			const donor = holders.get(fp).find(other => earlier(other, entry) && !samePerson(other, entry));

			if (!donor) {
				continue;
			}

			marks.push({ fp, donor });
			byDonor.set(donor, (byDonor.get(donor) ?? 0) + 1);
		}

		const share = marks.length / own.length;

		// Ниже нижнего порога пак чист. Одна совпавшая тема на тридцать — это
		// совпадение, а не находка: заводить из-за неё запись, ярлык и метки
		// у тем значило бы шуметь на всю библиотеку ради шума
		if (share < limits.plagiarismPartialShare) {
			continue;
		}

		const ranked = [...byDonor.entries()].sort((a, b) => b[1] - a[1] || a[0].id - b[0].id);
		const top = ranked[0][1] / marks.length;

		verdicts.set(entry.id, {
			// Три ступени, а не «да/нет».
			//
			//   pack     — копия: чужого почти всё, и почти всё от одного донора;
			//   compiled — солянка: чужого почти всё, но собрано из нескольких;
			//   partial  — заметная доля чужого при своём костяке.
			//
			// Разница между первыми двумя не косметическая: у копии один виноватый
			// и одна ссылка, у солянки их пять, и обещать ей «списано вот отсюда»
			// значило бы соврать. Третья же — не обвинение вовсе, а наблюдение,
			// и отбор «без копий чужих паков» её не трогает
			kind: share < limits.plagiarismShare
				? 'partial'
				: (top >= limits.plagiarismDonorShare ? 'pack' : 'compiled'),
			share: round(share),
			borrowed: marks.length,
			total: own.length,
			// Название донора лежит рядом с номером нарочно: адрес страницы пака
			// складывается из номера и названия (см. packSlug в src/slug.js), и без
			// названия карточке пришлось бы ходить в D1 за каждым донором отдельно
			sources: ranked.slice(0, MAX_SOURCES).map(([donor, n]) => ({
				id: donor.id,
				name: donor.name,
				n,
				share: round(n / marks.length),
			})),
			// Где в раундах стоят заимствованные темы и чьи они. Отсюда шаг
			// проставляет полю src номер донора: у солянки эти номера разные,
			// и каждая украденная тема получает свою ссылку
			places: marks.flatMap(({ fp, donor }) => entry.themes.get(fp).map(([r, t]) => ({
				round: r,
				theme: t,
				source: donor.id,
			}))),
		});

		stats.flagged++;
	}

	return { verdicts, stats };
}
