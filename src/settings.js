//
// config.js подмешивает этот объект в config целиком, поэтому в самом проекте
// ничего не изменилось: как было config.minGamesForDifficulty, так и осталось.

export const settings = {
	/** Сколько живёт вход, дни. */
	sessionDays: 30,

	/**
	 * Со скольких оценок показывать средний балл. До этого порога у пака видно
	 * только число проголосовавших: средним по двум-трём оценкам верить нельзя,
	 * а показанное число живёт своей жизнью и запоминается.
	 */
	minRatingsForScore: 10,

	/** Куда ведёт кнопка «Играть». */
	playerUri: 'https://sigame.vladimirkhil.com/',

	/**
	 * Сколько игр должно быть у пака, чтобы показывать сложность.
	 * При 100 оценку получает примерно каждый десятый пак, при 30 — каждый пятый.
	 * Уровни уже разобранных паков пересчитываются при запуске, переиндексация не нужна.
	 */
	minGamesForDifficulty: 100,

	/**
	 * Сколько всего вопросов должно быть показано по паку. Бывают паки, которые запускали
	 * полсотни раз, но почти не играли — там процент случаен и оценке верить нельзя.
	 */
	minShownForDifficulty: 300,

	/**
	 * Границы уровней сложности в процентах вопросов, на которые решились ответить.
	 * Доля правильных ответов для этого не годится: она почти у всех паков около 60%,
	 * потому что на трудный вопрос никто не жмёт и в этот процент он не попадает.
	 */
	difficultyThresholds: {
		easy: 65,   // больше 65% — лёгкий
		medium: 45, // 45..65 — средний
		hard: 30,   // 30..45 — сложный
		// меньше 30 — очень сложный
	},

	/**
	 * Доля правильных ответов, ниже которой пак считается на ступень сложнее.
	 * Отвечать-то на его вопросы решаются охотно — потому он и попадает в «лёгкие», —
	 * но отвечают мимо: за столом такой пак ощущается труднее, чем выглядит по
	 * одному проценту попыток. Ступень всего одна и ниже «очень сложного» не уходит.
	 */
	hardRightPercent: 50,

	/** С какой доли вопросов пак считается тематическим, а не солянкой. */
	topicThreshold: 0.6,

	/**
	 * С какой доли музыкальных вопросов пак считается музыкальным. Порог отдельный,
	 * потому что музыка не спорит с остальными тематиками: пак может быть
	 * одновременно аниме-паком на 100% и музыкальным на 90%.
	 */
	musicThreshold: 0.6,

	/**
	 * Со скольких тем франшиза считается повтором. Одна тема по «Наруто» в аниме-паке —
	 * это просто тема, а четыре подряд — уже перекос, ради которого всё и считается.
	 */
	franchiseMinThemes: 2,

	/**
	 * С какой доли вопросов франшиза считается преобладающей: тогда она выносится
	 * на карточку отдельным ярлыком («половина пака — это одно и то же»).
	 */
	franchiseDominantShare: 0.3,
};

/**
 * Имя уменьшенной копии обложки на хостинге.
 *
 * Формат один для всех — AVIF. Тот же кадр в нём весит вдвое меньше, чем в jpg
 * или webp, а обложки — самое тяжёлое, что отдаёт сайт: их под четыре сотни,
 * и на страницу их разом приходит два десятка. Браузер, который AVIF не понимает,
 * покажет вместо обложки квадрат с первой буквой названия (см. createLogo
 * в web/common.js) — некрасиво, но не сломано; таких браузеров с 2024 года нет.
 *
 * Правило лежит здесь, а не рядом со сборкой, потому что сойтись обязаны двое:
 * scripts/build-web.js под этим именем кладёт файл, cf/src/library.js под этим же
 * даёт на него ссылку. Разойдись они — обложек не будет ни одной.
 *
 * Расширение заменяется, а не приписывается: Content-Type Cloudflare ставит
 * по нему, и «511.jpg.avif» уехал бы как avif с jpg внутри.
 */
export function thumbName(logoFile) {
	return `${logoFile.replace(/\.[^./\\]*$/, '')}.avif`;
}

