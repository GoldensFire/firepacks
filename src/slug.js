// Название пака в адресе его страницы: «Аниме пак №5» → «anime-pak-5».
//
// Отдельным файлом, потому что считать его должны все трое: домашний сайт
// (src/server.js), его двойник на Cloudflare (cf/) и карта сайта, которую они
// отдают поисковикам. Браузер сюда не заглядывает вовсе — готовый кусок приезжает
// к нему вместе с паком (см. поле slug в toPackage), и второго набора правил
// перевода на сайте нет.
//
// Сам адрес паком не опознаётся: открывает страницу номер, стоящий перед
// названием, а название — для человека и поисковой выдачи. Поэтому пак, которого
// переименовали, по старой ссылке по-прежнему открывается.

/**
 * Русские буквы латиницей. Это не научная транслитерация, а то написание,
 * которое привычно читается в адресе: «щ» — «sch», «ю» — «yu».
 */
const TRANSLIT = {
	а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i',
	й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't',
	у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '',
	э: 'e', ю: 'yu', я: 'ya',
	// Украинские и белорусские буквы: паки с такими названиями в базе есть,
	// и без них от названия оставалась бы пара чёрточек
	і: 'i', ї: 'yi', є: 'ye', ґ: 'g', ў: 'u',
};

/** Сколько знаков названия остаётся в адресе. Дальше начинается не ссылка, а простыня. */
const MAX = 60;

/**
 * Кусок адреса по названию пака. Пустая строка — тоже ответ: у пака без названия
 * (и у названия из одних значков) адрес остаётся коротким, из одного номера.
 */
export function packSlug(name) {
	const slug = String(name ?? '')
		.toLowerCase()
		.replace(/[а-яёіїєґў]/g, letter => TRANSLIT[letter] ?? '')
		// Всё, что не буква и не цифра, становится чёрточкой: пробелы, знаки
		// препинания, эмодзи в названиях (их там хватает) и любая другая латиница
		// с диакритикой, которую в адресе видеть незачем
		.replace(/[^a-z0-9]+/g, '-')
		.replace(/^-+|-+$/g, '');

	if (slug.length <= MAX) {
		return slug;
	}

	// Обрезаем по границе слова, а не посередине: «anime-pak-po-garri-pott» читается
	// как ошибка, хотя это просто конец отведённой длины
	const cut = slug.slice(0, MAX);
	const border = cut.lastIndexOf('-');

	return (border > 20 ? cut.slice(0, border) : cut).replace(/-+$/, '');
}

/** Адрес страницы пака целиком: номер решает, какой пак, название — для читающего. */
export function packPath(id, name) {
	const slug = packSlug(name);
	return slug ? `/pack/${id}-${slug}` : `/pack/${id}`;
}

/**
 * Номер пака из адреса его страницы. Всё, что после номера, отбрасывается:
 * пак могли переименовать, ссылку — сократить руками, а открываться она должна
 * по-прежнему.
 */
export function packIdFromPath(pathname) {
	const found = /^\/pack\/(\d+)(?:[-/].*)?$/.exec(pathname);
	return found ? parseInt(found[1], 10) : null;
}
