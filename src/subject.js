/** Хвост названия, который называет часть, а не предмет: «2», «III», «X». */
const SEQUEL_TAIL = /\s+(?:\d+|[ivx]+)$/i;

/** Короче этого стем не укорачиваем: от «Ил 2» после отсечки осталось бы «ил». */
const MIN_STEM = 3;

/**
 * Чем отделяют подзаголовок от названия: двоеточием, слэшем или тире в пробелах.
 *
 * Точки здесь нет нарочно, хотя в franchise.js она есть. Там подзаголовок ищут
 * у названия темы, а здесь — у предмета пака, и предметы сплошь и рядом пишутся
 * с точками внутри: «S.T.A.L.K.E.R.», «Dr. House», «Музыка М. Ю. Елизарова».
 * Отсечка по точке оставила бы от них первую букву.
 */
const SUBTITLE = /\s*[:\/]\s*|\s+[-–—]\s+/;

/**
 * Название без подзаголовка: «Counter-Strike: Global Offensive» →
 * «Counter-Strike», «Судьба/Ночь схватки» → «Судьба».
 *
 * Ради этого всё и затевалось: подзаголовок называет ЧАСТЬ, а тип пака — это
 * предмет вообще, ровно как с номером части (см. SEQUEL_TAIL). «The Elder
 * Scrolls V: Skyrim» после отсечки подзаголовка и номера становится «The Elder
 * Scrolls» — тем самым, чем он и является.
 *
 * Отсекается только то, после чего осталось настоящее слово: у «AC/DC» голова
 * короче MIN_STEM, и она остаётся при своём хвосте.
 */
function rootOf(name) {
	const text = String(name ?? '');
	const at = text.search(SUBTITLE);

	if (at <= 0) {
		return text;
	}

	const head = normalize(text.slice(0, at));
	return head.replace(/[^\p{L}\p{N}]/gu, '').length >= MIN_STEM ? text.slice(0, at) : text;
}

/** Регистр, ё и знаки препинания не важны, а слова-двойники сводятся к одному. */
function normalize(name) {
	return String(name ?? '')
		.toLowerCase()
		.replace(/ё/g, 'е')
		.replace(/[^\p{L}\p{N}]+/gu, ' ')
		.trim()
		.split(' ')
		.map(word => SAME_WORDS.get(word) ?? word)
		.join(' ');
}

/** Кириллица в латиницу; латиница и цифры остаются как есть. */
export function toLatin(text) {
	let out = '';

	for (const char of String(text ?? '').toLowerCase()) {
		out += Object.hasOwn(TO_LATIN, char) ? TO_LATIN[char] : char;
	}

	return out;
}

/**
 * Под каким именем это написание известно списку двойников. Пустая строка —
 * незнакомое написание, и разбираться с ним будут общие правила.
 *
 * Спрашивается дважды: у самого названия и у него же без подзаголовка, — потому
 * что в списке стоит «cs go», а в базе лежит и «CS:GO», и просто «CS».
 */
function aliasOf(name) {
	const whole = normalize(name);

	if (ALIASES.has(whole)) {
		return ALIASES.get(whole);
	}

	const root = normalize(rootOf(name));
	return ALIASES.get(root) ?? '';
}

/**
 * Ключ, по которому два предмета считаются одним типом пака.
 * «Дота» и «Дота 2» → dota; «Ведьмак 3» → vedmak;
 * «Counter-Strike: Global Offensive» и «CS:GO» → counter strike.
 *
 * Порядок здесь такой: сперва известное написание сводится к своему имени
 * (ALIASES), потом отсекается подзаголовок, потом номер части. Именно в этом
 * порядке, а не наоборот: «CS:GO» без подзаголовка — это «CS», и списку
 * двойников его надо показать целиком, пока «GO» ещё при нём.
 *
 * Пустая строка значит «ключа нет»: сравнивать такой предмет не с чем.
 */
export function subjectKey(name) {
	let text = normalize(rootOf(aliasOf(name) || name));

	// Номер части может быть не один: «Готика 2 3» — такое в подписях бывает
	while (SEQUEL_TAIL.test(text)) {
		const shorter = text.replace(SEQUEL_TAIL, '');

		if (shorter.length < MIN_STEM) {
			break;
		}

		text = shorter;
	}

	return toLatin(text);
}

/**
 * Самое короткое из написаний. При равной длине выигрывает написанное
 * с большой буквы: модель приводит предмет то «Футбол», то «футбол», и строчная
 * буква в колонке фильтров читается как опечатка.
 */
const shortest = names => [...names].sort((a, b) => a.length - b.length
	|| Number(a[0] === a[0].toLowerCase()) - Number(b[0] === b[0].toLowerCase())
	|| a.localeCompare(b, 'ru'))[0];

/**
 * Как назвать группу.
 *
 * «Самое короткое написание» — правило верное, пока в группе одни только полные
 * имена: тип пака называется «Дота», а не «Дота 2». Но с тех пор как в группу
 * сходятся и сокращения, оно врёт: у Counter-Strike самое короткое написание —
 * «CS», и колонка фильтров показывала бы две буквы вместо названия игры.
 *
 * Поэтому имя ищется по старшинству:
 *   1. Имя из списка двойников, если хоть одно написание группы через него
 *      прошло: там оно и записано затем, чтобы называть группу.
 *   2. Написание, которое САМО и есть предмет, — то, чей ключ совпадает с ключом
 *      группы без всяких отсечек: «Counter-Strike», а не «Counter-Strike:
 *      Global Offensive». Среди таких — самое короткое.
 *   3. Самое короткое из оставшихся: у «Lineage 2» и «Lineage II» полного имени
 *      нет вовсе, и назвать группу можно только одной из частей.
 */
function groupName(names) {
	for (const name of names) {
		const alias = aliasOf(name);

		if (alias) {
			return alias;
		}
	}

	const key = subjectKey(names[0]);
	const whole = names.filter(name => toLatin(normalize(name)) === key);

	return shortest(whole.length > 0 ? whole : names);
}

/**
 * Сводит предметы в типы паков: одинаковый ключ — одна строка в колонке фильтров.
 *
 * @param {Array<{name: string, count: number}>} rows предметы как они лежат в базе
 * @returns {Array<{name: string, key: string, count: number, names: string[]}>}
 *   от частых к редким; names — все написания группы, ими и отбирается выдача
 */
export function groupSubjects(rows) {
	const groups = new Map();

	for (const row of rows ?? []) {
		const name = String(row.name ?? '').trim();
		const key = subjectKey(name);

		if (!name || !key) {
			continue;
		}

		let group = groups.get(key);

		if (!group) {
			group = { key, count: 0, names: [] };
			groups.set(key, group);
		}

		group.count += row.count ?? 0;
		group.names.push(name);
	}

	return [...groups.values()]
		.map(group => ({
			...group,
			names: [...group.names].sort(),
			name: groupName(group.names),
		}))
		.sort((a, b) => b.count - a.count || a.name.localeCompare(b.name, 'ru'));
}

// Сведения по вхождению одного имени в другое — «ДжоДжо» внутри «Невероятных
// приключений ДжоДжо» — здесь нет нарочно, хотя в franchise.js оно есть. Там
// оно работает внутри ОДНОГО пака, где все названия про одно и то же
// содержимое; здесь же имена приходят со всей базы, и правило ловит одно
// произведение на десяток посторонних совпадений: «Американский футбол»
// уезжал в «Футбол», «Советское кино» — в группу к рок-группе «Kino»,
// а «Зарубежная и отечественная музыка» — в «Русскую музыку». Такие пары
// сводятся поимённо, списком ALIASES: их немного, и каждая проверена глазами.

/**
 * Какие написания предмета отбирать, когда попросили тип пака. Нажали «Дота» —
 * выдача обязана показать и паки по «Доте 2»: это одна строка в колонке.
 *
 * Спросили о том, чего в базе нет, — возвращаем само спрошенное: пусть выдача
 * окажется пустой, а не всей базой.
 */
export function subjectMatches(groups, asked) {
	const name = String(asked ?? '').trim();

	if (!name) {
		return [];
	}

	const key = subjectKey(name);
	return groups.find(group => group.key === key)?.names ?? [name];
}
