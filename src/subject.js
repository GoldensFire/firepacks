// Дополнительные типы паков — те, что целиком про один предмет: «пак по Доте»,
// «пак по Вархаммеру», «пак по футболу». Здесь только сведение названий: сам
// предмет считает разметка тем (см. franchise.js и topics.js).
//
// Зачем это отдельно от franchise.js. Тот сводит написания ОДНОГО произведения:
// «Атака титанов» и «Shingeki no Kyojin» — одно и то же, а «Fate: Zero» и
// «Fate/Apocrypha» — части одного. Числа он при этом сверяет точно и нарочно:
// «Сезон 2» и «Сезон 3» отличаются одним символом, и склеивать их нельзя.
//
// Здесь вопрос другой — не «одно ли это произведение», а «один ли это тип пака».
// И на него ответ другой: пак по Доте и пак по Доте 2 в колонке фильтров стоят
// двумя строками по одному паку в каждой, хотя ищут их одним и тем же словом.
// Поэтому хвостовой номер части из ключа выбрасывается: тип пака — это «Дота».
//
// Заодно ключ переводится в латиницу. Названия предметов в базе почти сплошь
// русские (см. Names.display: русское написание предпочитается), а ищут их
// как придётся — «dota», «naruto», «vedmak»: раскладку переключать ради строки
// поиска никто не станет. Ключ уходит на сайт вместе с названием, и поиск
// в колонке фильтров сверяется с ним же (см. renderSubjects).
//
// Файл общий с двойником сайта на Cloudflare, как settings.js и keys.js:
// сведение обязано считаться одинаково с обеих сторон, иначе один и тот же
// пак попадал бы дома в «Дота», а наверху — в «Дота 2».

/**
 * Кириллица латиницей. Таблица нарочно простая, «как пишут»: щ → sch, х → h,
 * ц → c. Это не транслитерация по ГОСТу — это способ сравнить «дота» и «dota»,
 * и точность здесь нужна ровно та, с какой набирают в строке поиска.
 */
const TO_LATIN = {
	а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ж: 'zh', з: 'z',
	и: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p',
	р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'c', ч: 'ch',
	ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
	і: 'i', ї: 'i', є: 'e', ґ: 'g', ў: 'u',
};

/** Хвост названия, который называет часть, а не предмет: «2», «III», «X». */
const SEQUEL_TAIL = /\s+(?:\d+|[ivx]+)$/i;

/** Короче этого стем не укорачиваем: от «Ил 2» после отсечки осталось бы «ил». */
const MIN_STEM = 3;

/** Регистр, ё и знаки препинания не важны. */
function normalize(name) {
	return String(name ?? '')
		.toLowerCase()
		.replace(/ё/g, 'е')
		.replace(/[^\p{L}\p{N}]+/gu, ' ')
		.trim();
}

/** Кириллица в латиницу; латиница и цифры остаются как есть. */
export function toLatin(text) {
	let out = '';

	for (const char of String(text ?? '').toLowerCase()) {
		out += Object.hasOwn(TO_LATIN, char) ? TO_LATIN[char] : char;
	}

	return out;
}

/**
 * Ключ, по которому два предмета считаются одним типом пака.
 * «Дота» и «Дота 2» → dota; «Ведьмак 3» → vedmak.
 *
 * Пустая строка значит «ключа нет»: сравнивать такой предмет не с чем.
 */
export function subjectKey(name) {
	let text = normalize(name);

	// Номер части может быть не один: «Готика 2 3» — такое в подписях бывает
	while (SEQUEL_TAIL.test(text)) {
		const shorter = text.replace(SEQUEL_TAIL, '');

		if (shorter.length < MIN_STEM) {
			break;
		}

		text = shorter;
	}

	return toLatin(text);
}

/**
 * Сводит предметы в типы паков: одинаковый ключ — одна строка в колонке фильтров.
 *
 * Показывается самое короткое написание группы — то есть имя без номера части:
 * тип пака называется «Дота», а не «Дота 2», даже если паков по второй больше.
 * Это и есть смысл группы: она про предмет вообще, а не про конкретную часть.
 *
 * @param {Array<{name: string, count: number}>} rows предметы как они лежат в базе
 * @returns {Array<{name: string, key: string, count: number, names: string[]}>}
 *   от частых к редким; names — все написания группы, ими и отбирается выдача
 */
export function groupSubjects(rows) {
	const groups = new Map();

	for (const row of rows ?? []) {
		const name = String(row.name ?? '').trim();
		const key = subjectKey(name);

		if (!name || !key) {
			continue;
		}

		let group = groups.get(key);

		if (!group) {
			group = { key, count: 0, names: [] };
			groups.set(key, group);
		}

		group.count += row.count ?? 0;
		group.names.push(name);
	}

	return [...groups.values()]
		.map(group => ({
			...group,
			names: [...group.names].sort(),
			// Короткое имя — это имя предмета, длинное — имя его части
			name: [...group.names].sort((a, b) => a.length - b.length || a.localeCompare(b, 'ru'))[0],
		}))
		.sort((a, b) => b.count - a.count || a.name.localeCompare(b.name, 'ru'));
}

/**
 * Какие написания предмета отбирать, когда попросили тип пака. Нажали «Дота» —
 * выдача обязана показать и паки по «Доте 2»: это одна строка в колонке.
 *
 * Спросили о том, чего в базе нет, — возвращаем само спрошенное: пусть выдача
 * окажется пустой, а не всей базой.
 */
export function subjectMatches(groups, asked) {
	const name = String(asked ?? '').trim();

	if (!name) {
		return [];
	}

	const key = subjectKey(name);
	return groups.find(group => group.key === key)?.names ?? [name];
}
