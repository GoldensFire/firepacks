/**
 * Значок как элемент страницы. Прячется от чтения вслух: он всегда стоит рядом
 * с подписью или подсказкой, и второй раз называть то же самое незачем.
 */
function icon(name, className) {
	const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');

	svg.setAttribute('viewBox', '0 0 24 24');
	svg.setAttribute('aria-hidden', 'true');
	svg.setAttribute('focusable', 'false');
	svg.setAttribute('class', className ? `icon ${className}` : 'icon');
	svg.innerHTML = ICON_PATHS[name] ?? '';

	return svg;
}

/** Значок тематики: у солянки и неразмеченных паков он тоже есть. */
function topicIcon(key, className) {
	return icon(TOPIC_ICONS[key] ?? 'dice', className);
}

/**
 * Строка «значок + текст». Нужна там, где раньше стояло `${эмодзи} ${текст}`:
 * значок и подпись должны держаться вместе и не разъезжаться переносом.
 */
function iconText(name, text, className) {
	const box = element('span', className ? `icon-text ${className}` : 'icon-text');
	box.append(icon(name), element('span', null, String(text)));
	return box;
}
