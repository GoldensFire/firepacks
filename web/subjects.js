// Все паки, которые целиком про одно: полный список тем с числом паков у каждой.
//
// Зачем отдельная страница. Тот же список стоит в колонке фильтров библиотеки,
// но там он обрезан сороковкой (см. subjectLimit в src/settings.js) — колонка
// не список всего на свете, в ней смотрят, чего много. Беда в том, что список
// длинный, сотни строк, и всё любопытное в нём как раз в хвосте: «Цивилизация»,
// «Твин Пикс», «Вархаммер», «Фоллаут». Из колонки они пропадали молча, и найти
// их можно было только случайно наткнувшись на такой пак в выдаче — то есть
// никак. Здесь список целиком, и поиск идёт по нему же.
//
// Своих паков страница не показывает: нажатие уводит в библиотеку с уже
// поставленным отбором (/?subject=…), где всё остальное — сортировки, фильтры,
// карточки — работает как всегда.

'use strict';

/** Что приехало с сервера: весь список типов и порог, по которому он собран. */
let data = null;

/**
 * Регистр и ё при поиске не важны. Правило то же, что в колонке фильтров
 * библиотеки (см. normalize в web/app.js), и это не мелочь: списки здесь
 * и там один и тот же, и находиться в них должно одинаково.
 *
 * Знаки препинания и пробелы нарочно остаются на месте. Латинский ключ,
 * по которому тоже идёт поиск, собран из слов через пробел («sid meier s
 * civilization»), и выбрось мы пробелы — набранное «civilization» перестало
 * бы находить то, ради чего ключ и заведён.
 */
function normalize(text) {
	return String(text ?? '').toLowerCase().replace(/ё/g, 'е').trim();
}

function render() {
	const container = $('list');
	const filter = normalize($('subjectSearch').value);
	container.textContent = '';

	// Ищется и по названию, и по латинскому ключу: названия в базе почти сплошь
	// русские, а набирают их как придётся — «dota», «naruto», «vedmak». Ключ
	// считает сервер (см. src/subject.js), он же без номера части, поэтому
	// «dota» находит и «Доту», и «Доту 2» — то есть один и тот же тип пака
	const found = (data?.subjects ?? []).filter(item => !filter
		|| normalize(item.name).includes(filter)
		|| (item.key ?? '').includes(filter));

	for (const item of found) {
		// Настоящая ссылка, а не кнопка со скриптом: такую можно открыть
		// в соседней вкладке, положить в закладки и дать другому — а это
		// ровно то, что с ней и делают
		const link = element('a', 'subject-card');
		link.href = `/?subject=${encodeURIComponent(item.name)}`;
		link.title = `Паки, у которых «${item.name}» занимает не меньше `
			+ `${Math.round((data?.subjectPackShare ?? 0.5) * 100)}% вопросов`;

		link.append(
			icon('target', 'topic-icon'),
			element('span', 'subject-card__name', item.name),
			element('span', 'subject-card__count', String(item.count)),
		);

		container.append(link);
	}

	if (found.length === 0) {
		container.append(element('p', 'hint', filter
			? 'Ничего не нашлось. Попробуйте короче: «вар» вместо «вархаммер 40000».'
			: 'Появятся, когда паки разметит Gemini: тип берётся из предмета тем.'));
	}

	renderHint(found.length);
}

/**
 * Строка под заголовком. Говорит две вещи: сколько таких тем всего и по какому
 * правилу пак сюда попадает. Второе важнее первого — без него список читается
 * как «паки, где это упоминается», а это совсем другой, куда более длинный
 * список (см. subjectPackShare в src/settings.js).
 */
function renderHint(shown) {
	const total = data?.subjects?.length ?? 0;
	const share = Math.round((data?.subjectPackShare ?? 0.5) * 100);
	const counted = shown === total
		? `${total} ${plural(total, 'тема', 'темы', 'тем')}`
		: `${shown} из ${total}`;

	$('hint').textContent = `${counted}. Пак попадает сюда, когда одна тема занимает `
		+ `не меньше ${share}% его вопросов. В колонке фильтров библиотеки таких строк `
		+ `только ${data?.subjectLimit ?? 40} — самых частых; здесь весь список.`;
}

async function load() {
	try {
		data = await (await fetch('/api/subjects')).json();
	} catch {
		$('hint').textContent = 'Не удалось загрузить список.';
		return;
	}

	// От частых к редким: в списке из сотен строк первым делом смотрят,
	// про что паков больше всего, а поиск нужен уже тем, кто пришёл за своим
	data.subjects = (data.subjects ?? []).sort((a, b) => b.count - a.count || a.name.localeCompare(b.name, 'ru'));
	render();
}

// Поиск идёт по уже приехавшему списку, поэтому ждать здесь нечего: буква —
// и сразу выдача. Задержка в полсотни миллисекунд — не ради сервера, а чтобы
// не перерисовывать сотни строк на каждое нажатие клавиши
let searchTimer = null;

$('subjectSearch').addEventListener('input', () => {
	clearTimeout(searchTimer);
	searchTimer = setTimeout(render, 50);
});

// Шапка здесь та же, что и на всех остальных страницах сайта. Настройки ей нужны
// свои — счётчики и уголок входа, — а самому списку они ни за чем, и ждать
// их ему незачем
initTopbar();

load();
